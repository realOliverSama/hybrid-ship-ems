/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */
  uint8_t key, t = 0;
  uint8_t k, i = 0, j = 0;
  uint32_t rgbled_buf[10];
  /* USER CODE END 1 */

  /* Enable the CPU Cache */

  /* Enable I-Cache---------------------------------------------------------*/
  SCB_EnableICache();

  /* Enable D-Cache---------------------------------------------------------*/
  SCB_EnableDCache();

  /* MCU Configuration--------------------------------------------------------*/

  /* Update SystemCoreClock variable according to RCC registers values. */
  SystemCoreClockUpdate();
  HAL_Init();

  /* USER CODE BEGIN Init */
#ifdef DEBUG
  sys_clock_config_debug();
#endif

  /* USER CODE END Init */

  /* Update SystemCoreClock variable */
  SystemCoreClockUpdate();

  /* USER CODE BEGIN SysInit */
#ifdef DEBUG
  MX_XSPI1_Init();
  HyperRAM_Init(&HyperRAMObject, &hxspi1);
  HyperRAM_EnableMemoryMappedMode(&HyperRAMObject);
#endif

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_GPDMA1_Init();
  MX_DMA2D_Init();
  MX_TIM4_Init();
  MX_LTDC_Init();
  SystemIsolation_Config();
  /* USER CODE BEGIN 2 */
  led_init();                             /* 初始化LED */
  key_init();     							          /* 初始化按键 */
  ws2812b_init();                     		/* 初始化WS2812B */

  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
    key = key_scan(0);
    if(t % 100 == 0)                                    /* 间隔段时间换个颜色填充 */
    {
      LED0_TOGGLE();
      for(i = 0; i < LED_NUM; i++)
      {
        rgbled_buf[i] = g_grb888_color[j % LED_NUM];/* 颜色填充 */
      }
      for(k = 1; k <= LED_NUM; k++)
      {
        ws2812b_display(k, rgbled_buf);             /* 依次点亮RGBLED灯(流水灯效果) */
        HAL_Delay(50);
      }
      j++;                                            /* 颜色数组的下一个成员 */
      t = 0;
    }
    t++;

    if(key == WKUP_PRES)
    {
      ws2812b_reset();                                /* 复位所有灯，让其熄灭 */
    }
    HAL_Delay(10);
    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
  }
  /* USER CODE END 3 */
}

