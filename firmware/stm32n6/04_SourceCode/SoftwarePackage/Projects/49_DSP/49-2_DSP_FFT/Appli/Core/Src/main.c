/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */
  uint8_t t = 0;
  uint8_t key;
  float time;
  char buf[50];
  arm_cfft_radix4_instance_f32 scfft;
  uint16_t i;
  /* USER CODE END 1 */

  /* Enable the CPU Cache */

  /* Enable I-Cache---------------------------------------------------------*/
  SCB_EnableICache();

  /* Enable D-Cache---------------------------------------------------------*/
  SCB_EnableDCache();

  /* MCU Configuration--------------------------------------------------------*/

  /* Update SystemCoreClock variable according to RCC registers values. */
  SystemCoreClockUpdate();
  HAL_Init();

  /* USER CODE BEGIN Init */
#ifdef DEBUG
  sys_clock_config_debug();
#endif

  /* USER CODE END Init */

  /* Update SystemCoreClock variable */
  SystemCoreClockUpdate();

  /* USER CODE BEGIN SysInit */
#ifdef DEBUG
  MX_XSPI1_Init();
  HyperRAM_Init(&HyperRAMObject, &hxspi1);
  HyperRAM_EnableMemoryMappedMode(&HyperRAMObject);
#endif

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_DMA2D_Init();
  MX_LTDC_Init();
  MX_TIM6_Init();
  SystemIsolation_Config();
  /* USER CODE BEGIN 2 */
  led_init();     /* 初始化LED */
  key_init();     /* 初始化按键 */
  rgblcd_init();  /* 初始化RGB LCD */
  btim_timx_int_init(65535, 40000 - 1);  /* 初始化基本定时器中断 */

  rgblcd_show_string(30, 50, 200, 16, 16, "STM32", RED);
  rgblcd_show_string(30, 70, 200, 16, 16, "DSP FFT TEST", RED);
  rgblcd_show_string(30, 90, 200, 16, 16, "ATOM@ALIENTEK", RED);

  rgblcd_show_string(30, 110, 200, 16, 16, "WKUP:Run FFT", RED);
  rgblcd_show_string(30, 130, 200, 16, 16, "FFT runtime:", RED);

  /* FFT计算初始化 */
  arm_cfft_radix4_init_f32(&scfft, FFT_LENGTH, 0, 1);

  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
    key = key_scan(0);
    if (key == WKUP_PRES)
    {
      /* 生成输入数据 */
      for (i=0; i<FFT_LENGTH; i++)
      {
        fft_inputbuf[2 * i] = 100 +
                              10 * arm_sin_f32(2 * PI * i / FFT_LENGTH) +
                              30 * arm_sin_f32(2 * PI * i * 4 / FFT_LENGTH) +
                              50 * arm_cos_f32(2 * PI * i * 8 / FFT_LENGTH);
        fft_inputbuf[2 * i + 1] = 0;
      }

      /* FFT计算并计算耗时 */
      BTIM_TIMX->CNT = 0; /* 重设TI6定时器的计数器值 */
      g_timeout = 0;

      arm_cfft_radix4_f32(&scfft, fft_inputbuf);
      time = BTIM_TIMX->CNT + (uint32_t)g_timeout * 65536;
      sprintf(buf, "%fms\r\n", time / 10);
      rgblcd_show_string(126, 130, 200, 16, 16, buf, BLUE);

      /* 对FFT计算结果取模并通过串口输出 */
      arm_cmplx_mag_f32(fft_inputbuf, fft_outputbuf, FFT_LENGTH);
      printf("\r\n%d point FFT runtime:%.1fms\r\n", FFT_LENGTH, time / 10);
      printf("FFT Result:\r\n");
      for (i=0; i<FFT_LENGTH; i++)
      {
        printf("fft_outputbuf[%d]:%.1f\r\n", i, fft_outputbuf[i]);
      }
    }

    if (++t == 20)
    {
        t = 0;
        LED0_TOGGLE();
    }

    HAL_Delay(10);
    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
  }
  /* USER CODE END 3 */
}

