static uint32_t quantize_sample_rate(uint32_t sample_rate)
{
  uint32_t i;

  struct sample_rate_match {
    uint32_t match;
    uint32_t minimum;
    uint32_t maximum;
  } sample_rate_match_tbl[] = {
    {192000, 192000 - 6000, 192000 + 6000},
    {96000, 96000 - 1500, 96000 + 1500},
    {48000, 48000 - 1500, 48000 + 1500},
    {44100, 44100 - 1500, 44100 + 1500},
    {32000, 32000 - 1500, 32000 + 1500},
    {22050, 22050 - 1500, 22050 + 1500},
    {16000, 16000 - 1500, 16000 + 1500},
    {11025, 11025 - 1500, 11025 + 1500},
    {8000, 8000 - 1500, 8000 + 1500},
  };

  for (i = 0; i < (sizeof(sample_rate_match_tbl) / sizeof(sample_rate_match_tbl[0])); i++)
  {
    if ((sample_rate >= sample_rate_match_tbl[i].minimum) && (sample_rate <= sample_rate_match_tbl[i].maximum))
    {
      return sample_rate_match_tbl[i].match;
    }
  }

  return 0;
}

