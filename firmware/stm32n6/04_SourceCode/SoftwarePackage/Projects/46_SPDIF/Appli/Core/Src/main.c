/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */
  uint8_t t = 0;
  uint8_t spdifrx_sync_done_prev_flag = 1;
  uint32_t sample_rate;

  /* USER CODE END 1 */

  /* Enable the CPU Cache */

  /* Enable I-Cache---------------------------------------------------------*/
  SCB_EnableICache();

  /* Enable D-Cache---------------------------------------------------------*/
  SCB_EnableDCache();

  /* MCU Configuration--------------------------------------------------------*/

  /* Update SystemCoreClock variable according to RCC registers values. */
  SystemCoreClockUpdate();
  HAL_Init();

  /* USER CODE BEGIN Init */
#ifdef DEBUG
  sys_clock_config_debug();
#endif

  /* USER CODE END Init */

  /* Update SystemCoreClock variable */
  SystemCoreClockUpdate();

  /* USER CODE BEGIN SysInit */
#ifdef DEBUG
  MX_XSPI1_Init();
  HyperRAM_Init(&HyperRAMObject, &hxspi1);
  HyperRAM_EnableMemoryMappedMode(&HyperRAMObject);
#endif

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_GPDMA1_Init();
  MX_DMA2D_Init();
  MX_LTDC_Init();
  MX_SDMMC1_SD_Init();
  MX_SDMMC2_SD_Init();
  MX_USART1_UART_Init();
  MX_SAI1_Init();
  MX_SPDIFRX1_Init();
  SystemIsolation_Config();
  /* USER CODE BEGIN 2 */
  led_init();               /* 初始化LED */
  key_init();               /* 初始化按键 */
  uart_init(115200);        /* 初始化串口 */
  rgblcd_init();            /* 初始化RGB LCD */
  my_mem_init(SRAMIN);      /* 初始化AXISRAM1~2内存池 */
  my_mem_init(SRAMEX);      /* 初始化XSPI1 HyperRAM内存池 */
  es8388_init();            /* 初始化ES8388 */
  spdifrx_init();
  exfuns_init();            /* 初始化文件系统 */
  f_mount(fs[0], "0:", 1);  /* 挂载SD卡 */
  f_mount(fs[1], "1:", 1);  /* 挂载SD NAND */
  fonts_init();             /* 初始化字库 */

  rgblcd_show_string(30, 50, 200, 16, 16, "STM32", RED);
  rgblcd_show_string(30, 70, 200, 16, 16, "SPDIF", RED);
  rgblcd_show_string(30, 90, 200, 16, 16, "ATOM@ALIENTEK", RED);

  es8388_adda_cfg(1, 0);    /* 配置DAC/ADC使能 */
  es8388_output_cfg(1, 1);  /* 配置DAC输出通道使能 */
  es8388_hpvol_set(10);     /* 设置耳机音量 */
  es8388_spkvol_set(10);    /* 设置喇叭音量 */
  es8388_sai_cfg(0, 0);
  es8388_sai_clock_config(8000);
  es8388_sai_init_tx(1, 8000, 16);
  
  text_show_string(30, 110, 200, 16, "采样率: ", 16, 0, 0, RED);
  rgblcd_show_string(142, 110, 200, 16, 16, "Hz", BLUE);

  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
    if (spdifrx_sync_done_prev_flag == 0)
    {
      if (spdifrx_sync_is_done())
      {
        spdifrx_sync_done_prev_flag = 1;

        spdifrx_stop_sync();

        sample_rate = quantize_sample_rate(spdifrx_get_sample_rate());
        es8388_sai_clock_config(sample_rate);
        es8388_sai_init_tx(2, sample_rate, 24);

        spdifrx_rx_dma_cplt_user_cb_register(spdifrx_rx_dma_cplt_user_cb);
        es8388_sai_tx_dma_cplt_user_cb_register(es8388_sai_tx_dma_cplt_user_cb);
      
        spdifrx_rx_dma(&audio_buffer[audio_buffer_writer][0], AUDIO_BUFFER_SIZE / 4);
        es8388_sai_tx_dma(&audio_buffer[audio_buffer_reader][0], AUDIO_BUFFER_SIZE / 4);
      }
      else
      {
        spdifrx_sync();
      }
    }
    else
    {
      if (!spdifrx_sync_is_done())
      {
        spdifrx_sync_done_prev_flag = 0;

        spdifrx_rx_dma_cplt_user_cb_register(NULL);
        es8388_sai_tx_dma_cplt_user_cb_register(NULL);

        rgblcd_show_num(94, 110, 0, 6, 16, BLUE);
      }
      else
      {
        sample_rate = spdifrx_get_sample_rate();
        rgblcd_show_num(94, 110, sample_rate, 6, 16, BLUE);
      }
    }

    if (++t == 20)
    {
      t = 0;
      LED0_TOGGLE();
    }

    HAL_Delay(10);
    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
  }
  /* USER CODE END 3 */
}

