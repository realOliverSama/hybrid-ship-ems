/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */
  uint8_t t = 0;
  uint8_t key;
  uint8_t pwmdac_value;
  uint16_t pwmdac_voltage = 100;
  uint32_t adc_value;
  uint32_t adc_voltage;

  /* USER CODE END 1 */

  /* Enable the CPU Cache */

  /* Enable I-Cache---------------------------------------------------------*/
  SCB_EnableICache();

  /* Enable D-Cache---------------------------------------------------------*/
  SCB_EnableDCache();

  /* MCU Configuration--------------------------------------------------------*/

  /* Update SystemCoreClock variable according to RCC registers values. */
  SystemCoreClockUpdate();
  HAL_Init();

  /* USER CODE BEGIN Init */
#ifdef DEBUG
  sys_clock_config_debug();
#endif

  /* USER CODE END Init */

  /* Update SystemCoreClock variable */
  SystemCoreClockUpdate();

  /* USER CODE BEGIN SysInit */
#ifdef DEBUG
  MX_XSPI1_Init();
  HyperRAM_Init(&HyperRAMObject, &hxspi1);
  HyperRAM_EnableMemoryMappedMode(&HyperRAMObject);
#endif

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_DMA2D_Init();
  MX_LTDC_Init();
  MX_ADC1_Init();
  MX_TIM4_Init();
  SystemIsolation_Config();
  /* USER CODE BEGIN 2 */
  led_init();                         /* 初始化LED */
  key_init();                         /* 初始化按键 */
  rgblcd_init();                      /* 初始化RGB LCD */
  adc_init();                         /* 初始化ADC */
  pwmdac_init(256 - 1, 1 - 1);        /* 初始化PWMDAC */
  pwmdac_set_voltage(pwmdac_voltage); /* 设置PWMDAC输出电压 */

  rgblcd_show_string(30, 50, 200, 16, 16, "STM32", RED);
  rgblcd_show_string(30, 70, 200, 16, 16, "PWMDAC TEST", RED);
  rgblcd_show_string(30, 90, 200, 16, 16, "ATOM@ALIENTEK", RED);
  rgblcd_show_string(30, 110, 200, 16, 16, "WK_UP:+ KEY1:-", RED);
  rgblcd_show_string(30, 130, 200, 16, 16, "PWMDAC VAL:", BLUE);
  rgblcd_show_string(30, 150, 200, 16, 16, "PWMDAC VOL: 0.000V", BLUE);
  rgblcd_show_string(30, 170, 200, 16, 16, "ADC1_CH15_VOL: 0.000V", BLUE);

  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
    key = key_scan(0);
    if (key == WKUP_PRES)
    {
      /* 加大PWMDAC输出 */
      if (pwmdac_voltage < VDD_VALUE)
      {
        pwmdac_voltage += 100;
        pwmdac_set_voltage(pwmdac_voltage);
      }
    }
    else if (key == KEY1_PRES)
    {
      /* 减小PWMDAC输出 */
      if (pwmdac_voltage > 100)
      {
        pwmdac_voltage -= 100;
        pwmdac_set_voltage(pwmdac_voltage);
      }
    }

    if (++t == 20)
    {
      t = 0;

      /* 显示PWMDAC输出数字量 */
      pwmdac_value = (pwmdac_voltage * 256 - 1) / VDD_VALUE;
      rgblcd_show_xnum(118, 130, pwmdac_value, 3, 16, 0, BLUE);

      /* 显示PWMDAC输出模拟量 */
      rgblcd_show_xnum(126, 150, pwmdac_voltage / 1000, 1, 16, 0, BLUE);
      rgblcd_show_xnum(142, 150, pwmdac_voltage % 1000, 3, 16, 0x80, BLUE);

      /* 显示ADC采集模拟量 */
      adc_value = adc_get_result_average(ADC_CHANNEL_15, 10);
      adc_voltage = __HAL_ADC_CALC_DATA_TO_VOLTAGE(VREFINT_CAL_VREF, adc_value, ADC_RESOLUTION_12B);
      rgblcd_show_xnum(150, 170, adc_voltage / 1000, 1, 16, 0, BLUE);
      rgblcd_show_xnum(166, 170, adc_voltage % 1000, 3, 16, 0x80, BLUE);

      LED0_TOGGLE();
    }

    HAL_Delay(10);
    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
  }
  /* USER CODE END 3 */
}

