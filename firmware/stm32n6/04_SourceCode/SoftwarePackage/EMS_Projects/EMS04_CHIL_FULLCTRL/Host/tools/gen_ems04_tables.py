#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""gen_ems04_tables.py — EMS04 board constant-table generator.

Reads the S1 frozen f64 tables (exported by export_constants_table.m from the
frozen MATLAB entry points; see experiments/softhil_ems03_2026-09-25/ems04_s1/)
and emits C translation units for the board:

  bsfc_lut / soc_grid / dlam_grid  -> const double[] (kept f64, 4.7 KiB total;
      S1.5 proved these grids must NOT be f32-quantized: 368/376, 164/171,
      40/41 elements change bits under IEEE f32 round-to-nearest).
  policy_table_Pg (3020x66x3 f64)  -> palette[51] f64 + pg_idx[597960] u8
      (584 KiB instead of 4.56 MiB). Bit-level lossless BY CONSTRUCTION: the
      frozen Pg table holds exactly 51 unique values (dispatch grid 0:20:1000
      kW, S1.5 finding), so palette[idx[i]] reproduces the original double
      bit pattern exactly. Verify with check_ems04_tables.py.

The generator refuses to emit anything if a structural assumption breaks
(unique count > 256, unexpected element counts, non-finite values).

Run:  .venv_tf/bin/python Host/tools/gen_ems04_tables.py
Paths: relative to this script; override the S1 exported dir with the
EMS04_S1_EXPORTED_DIR environment variable if needed.
"""
import json
import os
import struct
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
# Host/tools -> project root is two levels up.
PROJ = os.path.normpath(os.path.join(HERE, "..", ".."))
# Project root -> repo root is six levels up:
# EMS04_CHIL_FULLCTRL -> EMS_Projects -> SoftwarePackage -> 04_SourceCode
# -> stm32n6 -> firmware -> repo root.
REPO = os.path.normpath(os.path.join(PROJ,
    "..", "..", "..", "..", "..", ".."))
EXPORTED_DEFAULT = os.path.join(
    REPO, "experiments", "softhil_ems03_2026-09-25", "ems04_s1", "exported")
EXPORTED = os.environ.get("EMS04_S1_EXPORTED_DIR", EXPORTED_DEFAULT)

APP_DIR = os.path.join(PROJ, "Appli", "App")
C_OUT = os.path.join(APP_DIR, "ems04_tables_gen.c")
H_OUT = os.path.join(APP_DIR, "ems04_tables_gen.h")

N_LAM, N_PBAR, N_REG = 3020, 66, 3
N_BSFC, N_SOC, N_DLAM = 376, 171, 41


def load_f64(name, expect_elems):
    path = os.path.join(EXPORTED, name)
    a = np.fromfile(path, dtype="<f8")
    if a.size != expect_elems:
        raise SystemExit("FAIL: %s has %d elems, expected %d"
                         % (name, a.size, expect_elems))
    if not np.all(np.isfinite(a)):
        raise SystemExit("FAIL: %s contains non-finite values" % name)
    return a


def hexlit(x):
    """Exact C99 hexadecimal float literal for a finite double."""
    return x.hex() + ""


def fmt_doubles(a, per_line):
    lits = [hexlit(float(v)) for v in np.asarray(a, dtype="<f8").ravel()]
    lines = []
    for i in range(0, len(lits), per_line):
        lines.append("  " + ", ".join(lits[i:i + per_line]) + ",")
    return "\n".join(lines)


def fmt_bytes(a, per_line):
    vals = [str(int(v)) for v in np.asarray(a, dtype=np.uint8).ravel()]
    lines = []
    for i in range(0, len(vals), per_line):
        lines.append("  " + ", ".join(vals[i:i + per_line]) + ",")
    return "\n".join(lines)


def main():
    print("exported dir: %s" % os.path.relpath(EXPORTED, REPO))
    pg = load_f64("policy_table_Pg.f64", N_LAM * N_PBAR * N_REG)
    bsfc = load_f64("bsfc_lut.f64", N_BSFC)
    socg = load_f64("soc_grid.f64", N_SOC)
    dlam = load_f64("dlam_grid.f64", N_DLAM)

    # ---- palette construction (bit-exact) ----
    palette, inv = np.unique(pg, return_inverse=True)  # sorted, unique f64
    palette = palette.astype("<f8")
    if palette.size > 256:
        raise SystemExit(
            "FAIL: Pg unique values = %d > 256; u8 palette inapplicable "
            "(S1.5 losslessness assumption broken — re-freeze needed)."
            % palette.size)
    idx = inv.astype(np.uint8)  # guard above guarantees 0..255
    # bit-exactness gate BEFORE emitting anything
    rebuilt = palette[idx]
    if rebuilt.tobytes() != pg.tobytes():
        n_bad = int(np.sum(rebuilt.view(np.uint64) != pg.view(np.uint64)))
        raise SystemExit("FAIL: palette reconstruction not bit-exact (%d)"
                         % n_bad)
    print("Pg: %d elems, %d unique, emitted palette+u8 index = %.1f KiB"
          % (pg.size, palette.size,
             (palette.nbytes + idx.nbytes) / 1024.0))

    # ---- emit header ----
    hdr = """\
/* ems04_tables_gen.h — AUTO-GENERATED by Host/tools/gen_ems04_tables.py
 * from the S1 frozen f64 exports (export_constants_table.m chain).
 * DO NOT EDIT BY HAND; regenerate instead. Source of truth:
 *   experiments/softhil_ems03_2026-09-25/ems04_s1/exported/ (f64 dumps)
 * Bit-exactness (palette[idx[i]] == policy_table_Pg.f64[i], all %d elems)
 * is checked by Host/tools/check_ems04_tables.py.
 */
#ifndef EMS04_TABLES_GEN_H
#define EMS04_TABLES_GEN_H

#include <stdint.h>

#ifdef __cplusplus
extern "C" {
#endif

#define EMS04_BSFC_LUT_N   %d
#define EMS04_SOC_GRID_N   %d
#define EMS04_DLAM_GRID_N  %d
#define EMS04_PG_PALETTE_N %d
#define EMS04_PG_INDEX_N   %d

extern const double         ems04_bsfc_lut[EMS04_BSFC_LUT_N];
extern const double         ems04_soc_grid[EMS04_SOC_GRID_N];
extern const double         ems04_dlam_grid[EMS04_DLAM_GRID_N];
extern const double         ems04_pg_palette[EMS04_PG_PALETTE_N];
extern const uint8_t        ems04_pg_index[EMS04_PG_INDEX_N];

#ifdef __cplusplus
}
#endif
#endif /* EMS04_TABLES_GEN_H */
""" % (pg.size, N_BSFC, N_SOC, N_DLAM, palette.size, idx.size)

    # ---- emit C source ----
    body = """\
/* ems04_tables_gen.c — AUTO-GENERATED by Host/tools/gen_ems04_tables.py
 * from the S1 frozen f64 exports. DO NOT EDIT BY HAND.
 * Doubles are emitted as C99 hex-float literals (exact IEEE-754 bit
 * round-trip). Pg is stored palette+index (see header); the accessor
 * ems04_pg_palette[ems04_pg_index[i]] is bit-identical to the original
 * f64 table by construction and verified element-wise offline.
 */
#include "ems04_tables_gen.h"

const double ems04_bsfc_lut[EMS04_BSFC_LUT_N] = {
%s
};

const double ems04_soc_grid[EMS04_SOC_GRID_N] = {
%s
};

const double ems04_dlam_grid[EMS04_DLAM_GRID_N] = {
%s
};

const double ems04_pg_palette[EMS04_PG_PALETTE_N] = {
%s
};

const uint8_t ems04_pg_index[EMS04_PG_INDEX_N] = {
%s
};
""" % (fmt_doubles(bsfc, 4),
       fmt_doubles(socg, 4),
       fmt_doubles(dlam, 4),
       fmt_doubles(palette, 4),
       fmt_bytes(idx, 20))

    with open(H_OUT, "w") as f:
        f.write(hdr)
    with open(C_OUT, "w") as f:
        f.write(body)
    print("wrote %s" % os.path.relpath(H_OUT, REPO))
    print("wrote %s (%.1f KiB)"
          % (os.path.relpath(C_OUT, REPO), os.path.getsize(C_OUT) / 1024.0))

    manifest = {
        "generator": "gen_ems04_tables.py",
        "exported_dir": os.path.relpath(EXPORTED, REPO),
        "palette_n": int(palette.size),
        "pg_elems": int(pg.size),
        "palette_bytes": int(palette.nbytes),
        "index_bytes": int(idx.nbytes),
        "small_tables_bytes": int(bsfc.nbytes + socg.nbytes + dlam.nbytes),
        "bit_exact_gate": "pre-emit reconstruction check passed",
    }
    res_dir = os.path.join(PROJ, "Host", "results", "ems04_tables")
    os.makedirs(res_dir, exist_ok=True)
    with open(os.path.join(res_dir, "tables_gen_manifest.json"), "w") as f:
        json.dump(manifest, f, indent=2)
    print("OK")


if __name__ == "__main__":
    sys.exit(main())
