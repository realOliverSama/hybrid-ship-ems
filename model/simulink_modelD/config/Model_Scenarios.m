%% ========================================================================
%  Model_Scenarios.m — HybridShip_Model_MVP 工况定义（集中管理）
%  每个工况满足：
%    1) 船舶位置从 0 m 开始；2) 船速从 0 m/s 开始；
%    3) 目标航速斜坡上升（无瞬时阶跃）；4) 达到目标后持续航行；
%    5) 航程达到 voyage_distance_m 后由 11_Voyage_Stop_Logic 终止仿真。
%  用法：
%    run('config/Model_Scenarios.m');   % 定义 SCENARIOS 与默认 SCN
%    SCN = SCENARIOS(7);                 % 选择指定工况
%  字段说明：
%    resistance_profile: 'const' 恒定 | 'inc' 渐增 | 'dec' 渐减 | 'step' 阶跃 | 'bands' 多段阻力带
%    profile_code: 0=const, 1=inc, 2=dec, 3=step, 4=bands
%    v_knots_x / v_knots_v: 目标航速剖面里程节点 [m] / 航速 [m/s]（最多 6 个，-1 结束）
%    accel_ramp_mps2 / decel_ramp_mps2: 目标航速加/减速斜坡率（时间域 Rate Limiter）
%    resistance_bands: [起点m 终点m 幅值] × 最多 4 段（起点 -1 表示结束）
%    current_knots_x / current_knots_v: 水流剖面里程节点 [m] / 水流速度 [m/s]（最多 4 个，-1 结束；默认单节点=恒定水流）
%  v2.1：服务航速 11 kn（5.66 m/s）；新增 S07 桥区机动 / S08 浅滩群 / S09 应急出动
%  v3.0（ECMS Phase 1 T-101）：新增时间序列航速剖面支持（S20 复合航次）：
%    speed_profile_mode: 'distance'（缺省，既有）| 'time'（时间序列表）
%    v_time_s / v_value_mps: 时间航速路点（分段恒定，过渡由 01_Scenario Rate Limiter 平滑）
%    current_time_s / current_value_mps: 时间水流路点（仅 S20 段 9 逆水 -1 m/s）
%    stop_time_s: 时间终止条件（S20 主终止；voyage_distance_m 放宽作里程核对）
% ========================================================================

