function scn = voyage_scn_v2(voyage)
% ecms25.voyage_scn_v2 — 数据集 v2 航次定义 -> Model D SCN 工况结构（T-302 / FR-301）
% 与 ecms2.voyage_scn 的唯一差异：阻力通道改用 bands 实现航次级恒定 k_res
% （t301 文档 §4 M3 实现决策：零模型改动）：
%   resistance_profile='bands' / profile_code=4 /
%   resistance_bands=[-100 1e6 k_res-1; -1 0 0; -1 0 0; -1 0 0] / rampT=1 s
%   起点设为负值（-100 m）→ x=0 起 r_up=1、r_dn=0 → 全程 m = 1 + (k_res-1) = k_res。
% 其余字段与 ecms2.voyage_scn 完全一致（VOYAGE_* 时间序列注入等）。
    scn = struct( ...
        'id', 2000 + voyage.id, 'name', voyage.name, ...
        'target_speed_mps', voyage.v_value_mps(end), ...
        'voyage_distance_m', 1e6, ...
        'river_current_mps', 0.0, ...
        'resistance_profile', 'bands', 'profile_code', 4, ...
        'resistance_change_position_m', 0, 'resistance_change_amplitude', 0, ...
        'resistance_change_ramp_time_s', 1, ...
        'hotel_kW', 100, 'initial_SOC', 0.60, 'random_seed', voyage.seed, ...
        'notes', sprintf('T-302 生成航次 %s (seed %d, k_res=%.4f)', ...
            voyage.name, voyage.seed, voyage.k_res), ...
        'v_knots_x', [0 -1 -1 -1 -1 -1], ...
        'v_knots_v', [voyage.v_value_mps(end) 0 0 0 0 0], ...
        'accel_ramp_mps2', voyage.accel_ramp_mps2, ...
        'decel_ramp_mps2', voyage.decel_ramp_mps2, ...
        'resistance_bands', [-100 1e6 voyage.k_res - 1; -1 0 0; -1 0 0; -1 0 0], ...
        'current_knots_x', [0 -1 -1 -1], 'current_knots_v', [0 0 0 0], ...
        'speed_profile_mode', 'time', ...
        'v_time_s', voyage.v_time_s, 'v_value_mps', voyage.v_value_mps, ...
        'current_time_s', voyage.current_time_s, ...
        'current_value_mps', voyage.current_value_mps, ...
        'stop_time_s', voyage.duration_s);
end
