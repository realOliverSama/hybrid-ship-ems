%CODE_SAFETY_INTERLOCK_E 返回 PMSSafetyInterlockE MATLAB Function block 源码字符串（Model E，T-004 链 C）
%   c = model.code_safety_interlock_e()
%   用途：builder 经 setMFCode 写入 16_Safety_Interlock MATLAB Function 块（T-007 集成层接线）；
%   纯 MATLAB 单测（scripts/tests/test_safety_interlock_e.m）亦以此字符串写盘直接调用。
%   依据：.specs/phase4-b-pms-safety/design.md §5.6（评审修订版，D-B14/D-B15）+ §2 裁决
%   （500 kW 口径 = genset-side 单机，DD-1）+ D-B7/D-B11；requirements.md FR-444~447。
%   采样约定：固定步 0.01 s，每步调用一次 = 1 tick；全部持续判据用整数 tick 计数
%   （PMS_S2_hold_ticks/PMS_S4_hold_ticks/PMS_start_fail_ticks 经入参传入，数值事实源
%   config/ModelE_Control_Parameters.m，T-001）；dt=0.01 硬编码于 tick 计数口径，
%   若模型固定步长变更须一并重推（同 GensetUnitE OQ-6 口径）。

lines = { ...
'function [force_start_req, force_start_reason, force_stop_req, force_stop_reason, fault_latch, ems_health_ok, baseline_fallback_active, baseline_fallback_reason, min_gen_surplus_unresolved, D_firm_kW, S2_supply_gap_kW, flag_soc_low, flag_vdc_low, flag_bat_passthrough] = PMSSafetyInterlockE(state_DG1, state_DG2, cmd_onoff_1, cmd_onoff_2, P_load_gen_kW, P_prop_dem_kW, P_hotel_kW, P_DG1_kW, P_DG2_kW, P_bat_dis_avail_g_kW, P_bat_chg_avail_g_kW, N_dispatch, SOC, Vdc_V, bat_flag_1, bat_flag_2, bat_flag_3, P_gen_ref_kW, ems_health_raw, nominal_is_ems, voyage_active, PMS_S2_hold_ticks, PMS_S4_hold_ticks, PMS_start_fail_ticks, PMS_firm_margin_kW, DG_P_rated_kW, DG_P_min_kW, ASSUMED_eta_rect)'
'%#codegen'
'% PMSSafetyInterlockE —— 16_Safety_Interlock 安全联锁（Model E, FR-444/445/446/447, design §5.6 评审修订版）'
'%   离散步长约定：每调用一次 = 1 tick = 0.01 s；dt=0.01 硬编码于全部 tick 计数口径，'
'%   若模型固定步长变更须一并重推（同 GensetUnitE OQ-6 口径）。'
'%   职责边界（FR-444 / design §5.6 / §5.7）：'
'%     (1) 16 号不直写 Plant——override 请求总线经 UnitDelay（0.01 s）回 07_PMS_v2 作'
'%         Commitment Supervisor / source selector 高优先级输入；本函数本体不管 UnitDelay，'
'%         一拍拍序断言（override(t) ⇒ t+0.01 s 恰好一拍到达、无代数环）移交集成层 T-007；'
'%     (2) 08_Undervolt_Derate 保持唯一执行性 propulsion limiter，本函数无推进限制输出'
'%         （与 08 无任何信号直连，两者作用通道完全分离，FR-446/design §5.7）；'
'%     (3) fault_latch 锁存至仿真结束：v1 无 run 内复位通道，登记 future extension（D-B11）。'
'%   机组状态枚举（同链 B GensetUnitE）：0=OFF 1=STARTING 2=SYNCHRONIZING 3=ON 4=COOLDOWN。'
'%   reason 枚举（force_start_reason / force_stop_reason）：'
'%     0=无 3=SAFETY_DG_FAULT 4=SAFETY_REALIZED_SUPPLY_DEFICIT'
'%     5=SAFETY_PROSPECTIVE_FIRM_CAPACITY_DEFICIT 6=SAFETY_MIN_GEN_SURPLUS。'
'%   baseline_fallback_reason 枚举：0=无 1=健康通道失效 2=P_gen_ref 非有限。'
'%   域约定（DD-1，canonical 域 = genset-side）：全部比较量在 genset 域；P_bat_*_avail_g 与'
'%   P_load_gen 已由 07 边界换算，本函数只做算术、不做 ÷η_rect 域转换；S4 的'
'%   (P_prop_dem+P_hotel)/ASSUMED_eta_rect 是 design §5.6 公式自身的组成部分（bus 侧'
'%   commanded demand → genset 域 firm-capacity 要求），不算域转换点。'
'%   输出向量约定：force_start_req/force_stop_req/fault_latch [1×2]（DG1,DG2）；'
'%   flag_bat_passthrough [1×3]；全 override/flag 事件经输出端口入日志（VI-1，D-B7）。'
'persistent fl_latch prev_state s2_cnt s4_cnt s1b_ticks prev_fstp fback_active fback_reason min_srp'
'if isempty(fl_latch)'
'    fl_latch = zeros(1,2);    % S1 故障锁存（锁存至仿真结束，v1 无 run 内复位，D-B11 登记 future extension）'
'    prev_state = zeros(1,2);  % 上一拍机组状态（S1a 判据用）'
'    s2_cnt = 0;               % S2 连续判据计数 [tick]'
'    s4_cnt = 0;               % S4 连续判据计数 [tick]'
'    s1b_ticks = zeros(1,2);   % S1b STARTING/SYNC 连续驻留计数 [tick]'
'    prev_fstp = zeros(1,2);   % 上一拍 force_stop_req（S1a 判据用）'
'    fback_active = 0;         % S5 baseline fallback 锁存（D-B11：v1 不自动恢复）'
'    fback_reason = 0;         % S5 首因锁定事件码（1=通道失效 2=ref 非有限）'
'    min_srp = 0;              % S3 单健康机 unresolved 锁存（FR-445 S3 known out-of-scope）'
'end'
''
'st = [state_DG1, state_DG2];'
'cmd = [cmd_onoff_1, cmd_onoff_2];'
'P_DG = [P_DG1_kW, P_DG2_kW];'
''
'% ---- S1 DG fault 检测（design §5.6，D-B7 修正后语义，非字面 state≠command）----'
'% 先于 override 计算并用上一拍 prev_state/prev_fstp 判定，避免拍内自反馈。'
'for i = 1:2'
'    % S1a 非预期丢失：自非 OFF 进入 OFF/COOLDOWN ∧ cmd_onoff==1 ∧ 无本方 force_stop 在令'
'    if prev_state(i) ~= 0 && (st(i) == 0 || st(i) == 4) && cmd(i) > 0.5 && prev_fstp(i) < 0.5'
'        fl_latch(i) = 1;'
'    end'
'    % S1b 启动失败：state∈{STARTING,SYNC} 连续计数（否则清零），≥ PMS_start_fail_ticks → 锁存'
'    if st(i) == 1 || st(i) == 2'
'        s1b_ticks(i) = min(s1b_ticks(i) + 1, PMS_start_fail_ticks);  % 封顶防溢出，判据不变'
'        if s1b_ticks(i) >= PMS_start_fail_ticks'
'            fl_latch(i) = 1;'
'        end'
'    else'
'        s1b_ticks(i) = 0;'
'    end'
'end'
''
'% 健康在线机组数（S3/S4 共用口径：state==3 且未锁存故障；STARTING/SYNC 不计入，design §5.6）'
'n_on_healthy = 0;'
'for i = 1:2'
'    if st(i) == 3 && fl_latch(i) < 0.5'
'        n_on_healthy = n_on_healthy + 1;'
'    end'
'end'
''
'% ---- S2 Realized supply deficit（design §5.6 评审重定义，D-B14）----'
'% gap = max(0, P_load_gen − ΣP_DGi_actual)：判据基于实际供电能力而非指令错配；'
'% P_gen_unserved（generation-command mismatch）仅为 Dispatch 诊断量，禁用作本判据'
'% （design 反例：EMS 过度请求 800 kW 而实际负荷 300 kW 时 unserved>0 但无真实缺口）。'
'gap = P_load_gen_kW - (P_DG(1) + P_DG(2));'
'if gap < 0'
'    gap = 0;'
'end'
'S2_supply_gap_kW = gap;'
'if gap > P_bat_dis_avail_g_kW'
'    s2_cnt = min(s2_cnt + 1, PMS_S2_hold_ticks);  % 连续计数（封顶防溢出，判据不变）'
'else'
'    s2_cnt = 0;'
'end'
's2_trig = s2_cnt >= PMS_S2_hold_ticks;'
''
'% ---- S4 Prospective firm-capacity deficit（design §5.6 公式，FR-445 S4）----'
'% P_load_req_gen = (P_prop_dem + P_hotel)/ASSUMED_eta_rect：÷η_rect 是 §5.6 公式自身'
'% 组成部分（见文件头域约定注释，DD-1）；firm_avail 只计 ON 健康机组（STARTING/SYNC 不计入）。'
'% S4 是 capacity adequacy 判据，不是 instantaneous ramp adequacy（ramp/τ 瞬态缺口归'
'% battery/S2/Vdc 链，design §5.6）。'
'P_load_req_gen = (P_prop_dem_kW + P_hotel_kW) / ASSUMED_eta_rect;'
'firm_avail = n_on_healthy * DG_P_rated_kW + P_bat_dis_avail_g_kW;'
'D_firm_kW = P_load_req_gen + PMS_firm_margin_kW - firm_avail;'
'if D_firm_kW > 0'
'    s4_cnt = min(s4_cnt + 1, PMS_S4_hold_ticks);'
'else'
'    s4_cnt = 0;'
'end'
's4_trig = s4_cnt >= PMS_S4_hold_ticks;'
''
'% ---- S3 Min generation surplus（FR-445 S3，design §5.6）----'
'surplus_margin = N_dispatch * DG_P_min_kW - P_load_gen_kW;'
's3_cond = surplus_margin > P_bat_chg_avail_g_kW;'
''
'% ---- S5 EMS health fallback（design §5.6，D-B15 显式通道口径）----'
'% ems_health_ok = 显式健康通道有效 ∧ isfinite(P_gen_ref_kW)；isfinite 覆盖 NaN/±Inf，'
'% 对健康通道本身也做 isfinite 防御；不做 temporal freeze inference（D-B11/D-B15：'
'% legacy 变体可合法长时输出常数，常值输出≠控制器死亡，freeze/heartbeat 契约待 F 包定义）。'
'raw_ok = (ems_health_raw > 0.5) && isfinite(ems_health_raw);'
'ems_health_ok = 0;'
'if raw_ok && isfinite(P_gen_ref_kW)'
'    ems_health_ok = 1;'
'end'
'% 仅当 nominal source==EMS_AGGREGATE 时 S5 产生 fallback（BASELINE_POLICY 模式下'
'% selector 本不消费 EMS 输出，健康恶化为非事件：不置位、不报警）；'
'% fallback 锁存不自动恢复（D-B11），fallback_reason 首因锁定。'
'if ems_health_ok < 0.5 && nominal_is_ems > 0.5'
'    if fback_active < 0.5'
'        fback_active = 1;'
'        if raw_ok'
'            fback_reason = 2;   % P_gen_ref 非有限'
'        else'
'            fback_reason = 1;   % 健康通道失效（含 raw 非有限）'
'        end'
'    end'
'end'
''
'% ---- force_start 目标选择（确定性：available∧healthy∧offline）----'
'% target_i = state_i==0 且 fault_latch_i<0.5；COOLDOWN(4) 不可作目标（Plant 忽略启动指令）。'
'tgt = zeros(1,2);'
'for i = 1:2'
'    if st(i) == 0 && fl_latch(i) < 0.5'
'        tgt(i) = 1;'
'    end'
'end'
''
'% ---- force_start 请求（优先级 S1 响应 > S2 > S4；同拍 S2、S4 同时触发 reason 取 4）----'
'fs_req = zeros(1,2);'
'fs_reason = 0;'
'% S1 响应：机组 i 故障锁存 → 另一机 j 满足 voyage_active∧target_j → force_start（reason=3）'
'if fl_latch(1) > 0.5 && voyage_active > 0.5 && tgt(2) > 0.5'
'    fs_req(2) = 1;'
'    fs_reason = 3;'
'end'
'if fl_latch(2) > 0.5 && voyage_active > 0.5 && tgt(1) > 0.5'
'    fs_req(1) = 1;'
'    fs_reason = 3;'
'end'
'% S2 触发：优先 DG2（target_2），否则 DG1（target_1）；无目标 → 请求=0（flag-only，'
'% 缺口仍由 S2_supply_gap_kW 记录）'
'if s2_trig'
'    if tgt(2) > 0.5'
'        if fs_req(2) < 0.5'
'            fs_req(2) = 1;'
'            if fs_reason == 0'
'                fs_reason = 4;'
'            end'
'        end'
'    elseif tgt(1) > 0.5'
'        if fs_req(1) < 0.5'
'            fs_req(1) = 1;'
'            if fs_reason == 0'
'                fs_reason = 4;'
'            end'
'        end'
'    end'
'end'
'% S4 触发：同目标逻辑（reason=5；双机 ON 或无可启机组 → flag-only）'
'if s4_trig'
'    if tgt(2) > 0.5'
'        if fs_req(2) < 0.5'
'            fs_req(2) = 1;'
'            if fs_reason == 0'
'                fs_reason = 5;'
'            end'
'        end'
'    elseif tgt(1) > 0.5'
'        if fs_req(1) < 0.5'
'            fs_req(1) = 1;'
'            if fs_reason == 0'
'                fs_reason = 5;'
'            end'
'        end'
'    end'
'end'
''
'% ---- force_stop 请求（S1 防御性 FORCE_STOP 故障机 reason=3；S3 触发 FORCE_STOP DG2'
'%      reason=6；同拍时 reason 取 3——veto 最高优先级）----'
'fstp_req = zeros(1,2);'
'fstp_reason = 0;'
'if fl_latch(1) > 0.5'
'    fstp_req(1) = 1;'
'    fstp_reason = 3;'
'end'
'if fl_latch(2) > 0.5'
'    fstp_req(2) = 1;'
'    fstp_reason = 3;'
'end'
'if s3_cond'
'    if n_on_healthy >= 2'
'        fstp_req(2) = 1;   % 停 lag 机 DG2（旁路 dwell 由 Commitment 处理，design §5.6 S3）'
'        if fstp_reason == 0'
'            fstp_reason = 6;'
'        end'
'    else'
'        % 条件成立但仅单健康在线机：禁止 force_stop（FR-445 S3 + FR-439 N_DG_on≥1，'
'        % 单健康机不得造成 0DG）→ flag-only 并登记 known out-of-scope condition。'
'        min_srp = 1;'
'    end'
'end'
''
'% ---- 纯监视 flag（FR-446：flag 入日志、不独立动作；阈值 spec 字面冻结）----'
'flag_soc_low = 0;'
'if SOC <= 0.20'
'    flag_soc_low = 1;'
'end'
'flag_vdc_low = 0;'
'if Vdc_V < 600'
'    flag_vdc_low = 1;'
'end'
'flag_bat_passthrough = zeros(1,3);'
'if bat_flag_1 > 0.5'
'    flag_bat_passthrough(1) = 1;'
'end'
'if bat_flag_2 > 0.5'
'    flag_bat_passthrough(2) = 1;'
'end'
'if bat_flag_3 > 0.5'
'    flag_bat_passthrough(3) = 1;'
'end'
''
'% ---- 输出与拍序状态更新 ----'
'force_start_req = fs_req;'
'force_start_reason = fs_reason;'
'force_stop_req = fstp_req;'
'force_stop_reason = fstp_reason;'
'fault_latch = fl_latch;'
'baseline_fallback_active = fback_active;'
'baseline_fallback_reason = fback_reason;'
'min_gen_surplus_unresolved = min_srp;'
'prev_fstp = fstp_req;   % 供下一拍 S1a 判定"无 force_stop 在令"'
'prev_state = st;        % 供下一拍 S1a 判定"自非 OFF"'
'end'};
c = strjoin(lines, newline);
end