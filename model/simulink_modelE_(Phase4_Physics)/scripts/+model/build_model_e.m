        '    end\n' ...
        'end\n' ...
        '%% 每个 0.01 s 步输出\n' ...
        'P_ff = 0; t_fire_out = -1;\n' ...
        'if ev_active\n' ...
        '    if t > ev_tPeakAbs + ASSUMED_Gen_TimeConstant\n' ...
