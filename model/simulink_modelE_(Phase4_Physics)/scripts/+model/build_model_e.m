function setMFCode(blkPath, code, paramNames, paramSizes, twoPass)
% 通过 Stateflow.EMChart 设置 MATLAB Function 块代码（R2026a 新式块）
% 并声明工作区参数（Stateflow.Data, Scope=Parameter）
%   twoPass=true 时启用两遍写入（R2026a 参数端口固化规避，仅 law=7 内联图需要）；
%   其余图保持旧单遍路径（二次写入会破坏无参/少参图的维度传播状态）。
    if nargin < 3, paramNames = {}; end
    if nargin < 4, paramSizes = {}; end
    if nargin < 5, twoPass = false; end
    rt = sfroot;
    ch = rt.find('-isa', 'Stateflow.EMChart', 'Path', blkPath);
    if numel(ch) ~= 1
        error('MATLAB Function 块未找到: %s', blkPath);
    end
    ch.Script = code;
    % 参数声明：脚本解析会自动把未声明标识符生成为 Input 数据，
    % 这里将其改写为 Parameter 作用域（不存在则新建）
    ds = ch.find('-isa', 'Stateflow.Data');
    for i = 1:numel(paramNames)
        d = [];
        for j = 1:numel(ds)
            if strcmp(ds(j).Name, paramNames{i})
                d = ds(j);
                break;
            end
        end
        if isempty(d)
            d = Stateflow.Data(ch);
            d.Name = paramNames{i};
        end
        d.Scope = 'Parameter';
        if numel(paramSizes) >= i && ~isempty(paramSizes{i})
            d.Props.Array.Size = paramSizes{i};
        end
    end
    % 两遍写入（R2026a 行为规避，2026-08-26）：第一遍赋值时未声明标识符会被
    % 生成为 Input Data 并固化进函数签名；仅改 Scope=Parameter 不会收缩签名，
    % 导致参数变成悬空端口（收 0 值而非 workspace 参数）。第二遍重写同文本时
    % 这些标识符已是 Parameter，Stateflow 以正确的签名重建接口。
    % 仅对声明 twoPass=true 且有参数名单的图启用两遍写入。
    if twoPass && ~isempty(paramNames)
        ch.Script = code;
        ds = ch.find('-isa', 'Stateflow.Data');
        for i = 1:numel(paramNames)
            for j = 1:numel(ds)
                if strcmp(ds(j).Name, paramNames{i})
                    ds(j).Scope = 'Parameter';
                    break;
                end
            end
        end
    end
end

