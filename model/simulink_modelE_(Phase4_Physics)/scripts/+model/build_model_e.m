function buildEMSControllerC(mdl, pos)
% 05_EMS_Controller: Variant Subsystem（EMS_CTRL_LAW 选 Baseline/AI/ScheduledFF/FixedECMS/SOCAdaptiveECMS/OracleECMS/NN-AECMS；EMS_WORK_MODE 选 手动/半自动/全自动）
% EMS_CTRL_LAW: 0=EMS_Baseline(无预测) 1=EMS_AI_Enhanced(即时前馈) 2=EMS_ScheduledFF(定时前馈, T-004)
%               4=EMS_Fixed_ECMS（单步网格穷举 ECMS，T-103，design §3.1）
%               5=EMS_SOC_Adaptive_ECMS（λ(t)=λ₀+K_soc·(SOC_ref−SOC)，T-105，design §3.2）
%               6=EMS_Oracle_ECMS（law=5 + K_E·ê_future，T-106，design §3.2；oracle 上界验证，非实时可实现 E5）
%               7=EMS_NN_AECMS（law=6 v2 同构 + extrinsic ê_NN，T-204，design §5，FR-208；Amendment v1.2 兜底）
    sys = [mdl '/05_EMS_Controller'];
    add_block('simulink/Ports & Subsystems/Variant Subsystem', sys, 'Position', pos);
    % 变体选择（默认子模块路径由掩码提供）
    set_param([sys '/Subsystem'],  'VariantControl', 'EMS_CTRL_LAW == 1');
    set_param([sys '/Subsystem1'], 'VariantControl', 'EMS_CTRL_LAW == 0');
    set_param([sys '/Subsystem'],  'Name', 'EMS_AI_Enhanced');
    set_param([sys '/Subsystem1'], 'Name', 'EMS_Baseline');
    % 第三变体 EMS_ScheduledFF：新增 Subsystem2 子模块，VariantControl 注册为 choice
    add_block('simulink/Ports & Subsystems/Subsystem', [sys '/Subsystem2'], 'Position', [40 40 120 120]);
    set_param([sys '/Subsystem2'], 'VariantControl', 'EMS_CTRL_LAW == 2');
    set_param([sys '/Subsystem2'], 'Name', 'EMS_ScheduledFF');
    % 第四变体 EMS_Fixed_ECMS（T-103）：Subsystem3，VariantControl=EMS_CTRL_LAW == 4
    add_block('simulink/Ports & Subsystems/Subsystem', [sys '/Subsystem3'], 'Position', [160 40 240 120]);
    set_param([sys '/Subsystem3'], 'VariantControl', 'EMS_CTRL_LAW == 4');
    set_param([sys '/Subsystem3'], 'Name', 'EMS_Fixed_ECMS');
    % 第五变体 EMS_SOC_Adaptive_ECMS（T-105）：Subsystem4，VariantControl=EMS_CTRL_LAW == 5
    add_block('simulink/Ports & Subsystems/Subsystem', [sys '/Subsystem4'], 'Position', [280 40 360 120]);
    set_param([sys '/Subsystem4'], 'VariantControl', 'EMS_CTRL_LAW == 5');
    set_param([sys '/Subsystem4'], 'Name', 'EMS_SOC_Adaptive_ECMS');
    % 第六变体 EMS_Oracle_ECMS（T-106）：Subsystem5，VariantControl=EMS_CTRL_LAW == 6
    %   前瞻信号 ê_future 经变体内 From Workspace 读 ECMS_EHat_Data（oracle 专用通道，
    %   与 AI_Oracle_Data 通道分离，design §3.2；E5 红线：非实时可实现，仅上界验证）
    add_block('simulink/Ports & Subsystems/Subsystem', [sys '/Subsystem5'], 'Position', [400 40 480 120]);
    set_param([sys '/Subsystem5'], 'VariantControl', 'EMS_CTRL_LAW == 6');
    set_param([sys '/Subsystem5'], 'Name', 'EMS_Oracle_ECMS');
    % 第七变体 EMS_NN_AECMS（T-204，Phase 2；design Amendment v1.2 extrinsic 兜底）：Subsystem6，VariantControl=EMS_CTRL_LAW == 7
    %   NN 预测型 A-ECMS（design §5，FR-208）：与 law=6 v2 同构（SOC_ref 通道 + λ 钳位），
    %   唯一差别 ê 来源——coder.extrinsic 调 ecms2.nn_predict_ehat（300 s P_load 环形缓冲
    %   + v_ship + accel + 归一化 + MLP 前向，MATLAB 解释器执行）；权重经
    %   config/ecms_nn_weights.mat 运行期惰性 load（缺失 -> ê=0 回退 ≡ law=5）
    add_block('simulink/Ports & Subsystems/Subsystem', [sys '/Subsystem6'], 'Position', [520 40 600 120]);
    set_param([sys '/Subsystem6'], 'VariantControl', 'EMS_CTRL_LAW == 7');
    set_param([sys '/Subsystem6'], 'Name', 'EMS_NN_AECMS');
    inames = {'P_load_total_kW','SOC','v_cmd_mps','v_ship_mps','acceleration_mps2','x_ship_m','t'};
    for k = 1:7
        ch = emsVariantPath(sys, k);
        % 清空默认端口
        d = find_system(ch, 'SearchDepth', 1, 'BlockType', 'Inport');
        for i = 1:numel(d), delete_block(d{i}); end
        d = find_system(ch, 'SearchDepth', 1, 'BlockType', 'Outport');
        for i = 1:numel(d), delete_block(d{i}); end
        for j = 1:numel(inames)
            add_block('simulink/Sources/In1', [ch '/' inames{j}], 'Position', [10 10+40*(j-1) 40 30+40*(j-1)]);
        end
        add_block('simulink/Sinks/Out1', [ch '/P_gen_ref_kW'], 'Position', [330 10 360 30]);
        if k == 1
            buildBaselineVariant(ch);
        elseif k == 2
            buildAIVariant(ch);
        elseif k == 3
            buildScheduledFFVariant(ch);
        elseif k == 4
            buildFixedECMSVariant(ch);
        elseif k == 5
            buildSOCAdaptiveECMSVariant(ch);
        elseif k == 6
            buildOracleECMSVariant(ch);
        else
            buildNNECMSVariant(ch);
        end
    end
    % 同步父级接口端口，并清理掩码遗留端口
    slprivate('variantfixes', 'MissingPorts', sys, 'addPorts', 'IOConnPort');
    for k = 1:7
        ch = emsVariantPath(sys, k);
        for nm = {'In1', 'Out1'}
            try, delete_block([ch '/' nm{1}]); catch, end
        end
    end
    cleanupVariantPorts(sys, inames, {'P_gen_ref_kW'});
end

function ch = emsVariantPath(sys, k)
% 变体序号 -> 子模块路径（k=1..7；4=EMS_Fixed_ECMS T-103，5=EMS_SOC_Adaptive_ECMS T-105，6=EMS_Oracle_ECMS T-106，7=EMS_NN_AECMS T-204）
    switch k
        case 1
            ch = [sys '/EMS_Baseline'];
        case 2
            ch = [sys '/EMS_AI_Enhanced'];
        case 3
            ch = [sys '/EMS_ScheduledFF'];
        case 4
            ch = [sys '/EMS_Fixed_ECMS'];
        case 5
            ch = [sys '/EMS_SOC_Adaptive_ECMS'];
        case 6
            ch = [sys '/EMS_Oracle_ECMS'];
        otherwise
            ch = [sys '/EMS_NN_AECMS'];
    end
end

