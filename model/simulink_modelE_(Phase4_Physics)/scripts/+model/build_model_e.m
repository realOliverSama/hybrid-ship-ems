%% ========================================================================
%  10_build_modelE.m 的构建函数 — 从零重建 HybridShip_ModelE.slx
%  Model D = Model A 功率流 + 闭环直流母线电气层（聚合单母线 750 V）
%  电气层: 13_DC_Bus(电容积分) + 14_Battery_Converter(下垂稳压) +
%         08_Undervolt_Derate(欠压降额) + 15_Bus_Voltage_Monitor(CCS 判据)
%  顶层接线（2026-10-15 可读性重构）：16 模块 From/Goto 总线制——模块输入左侧
%  接 From(tag)、输出右侧接 Goto(tag)，无消费者输出直接接 Terminator；
%  模块 4×4 网格 + 编译后 layoutTopLevel 端口对齐与正交布线。连接关系与
%  旧直连版逐一等价（From/Goto 无延迟/滤波），gate 数值不变。
%  自包含（复制 Model A 构建器修改而成）；Model A 行为不受影响。
%  依赖: config/Model_Parameters.m, config/Model_Scenarios.m
%  输出: model/HybridShip_ModelE.slx, reports/parameter_audit.csv
%  说明: 删除旧模型后完全重建；构建过程不使用任何 GUI 操作。
% ========================================================================
function build_model_e(ROOT)
% model.build_model_e - 从零重建 HybridShip_ModelE.slx（可重复执行）
% 依赖: config/Model_Parameters.m, config/Model_Scenarios.m
% 输出: model/HybridShip_ModelE.slx, reports/parameter_audit.csv
if nargin < 1
    ROOT = fileparts(fileparts(fileparts(mfilename('fullpath'))));
end
addpath(fullfile(ROOT, 'config'), fullfile(ROOT, 'scripts'));
% 配置脚本必须在基础工作区执行：模块参数表达式在 base 中求值
evalin('base', sprintf('run(''%s'')', fullfile(ROOT, 'config', 'ModelE_Physics_Parameters.m')));
% Phase 4-B（T-001, FR-451）：控制侧参数事实源，必须在物理参数之后、场景之前加载
% （PMS_*/Manual/Selector 参数 + DERIVED 阈值/ tick 换算，引用物理事实源变量）
evalin('base', sprintf('run(''%s'')', fullfile(ROOT, 'config', 'ModelE_Control_Parameters.m')));
evalin('base', sprintf('run(''%s'')', fullfile(ROOT, 'config', 'ModelE_TestScenarios.m')));
model.write_config_manifest(ROOT, ModelE_Sensitivity_Profile());   % design §2：每次 build 写 manifest

MDL = 'HybridShip_ModelE';
mdlPath = fullfile(ROOT, 'model', [MDL '.slx']);
if ~exist(fullfile(ROOT, 'model'), 'dir'), mkdir(fullfile(ROOT, 'model')); end

% ---- 清理旧模型 ----
if bdIsLoaded(MDL), close_system(MDL, 0); end
if exist(mdlPath, 'file'), delete(mdlPath); end

fprintf('[10] 开始重建 %s\n', mdlPath);
try
    %% ================= 1. 新建模型与求解器配置 =================
    new_system(MDL);
    load_system(MDL);
    set_param(MDL, 'SolverType', 'Fixed-step', 'Solver', 'ode3', ...
        'FixedStep', '0.01', 'StopTime', '7200', ...
        'SignalLogging', 'on', 'SignalLoggingName', 'logsout', ...
        'SaveOutput', 'off', 'SaveTime', 'off', 'ReturnWorkspaceOutputs', 'on', ...
        'AlgebraicLoopMsg', 'error', 'UnconnectedInputMsg', 'none', ...
        'UnconnectedOutputMsg', 'none', 'SolverPrmCheckMsg', 'error');

    % EMS 变体构建期间需要 AI 变体（7 端口）处于激活状态
    assignin('base', 'EMS_CTRL_LAW', 1);   % 0=Baseline 1=AI_Enhanced 2=ScheduledFF
    assignin('base', 'EMS_MODE', 1);       % 兼容列：= double(EMS_CTRL_LAW>0)
    % 若存在训练产物，则以最佳窗口与真实权重构建（source=3 环内推理自适应）
    if model.load_mlp_weights(ROOT)
        fprintf('[10] 检测到 mlp_weights.mat：MLP_Window=%d（权重与窗口已载入 base）\n', evalin('base', 'MLP_Window'));
    end

    %% ================= 2. 构建 16 个子系统（4×4 网格） =================
    % 2026-10-15 可读性重构：模块间改 From/Goto 总线制接线（见 wireTopLevel）；
    % 列距 420 为每列右侧 Goto / 次列左侧 From 预留走廊，模块高度按端口数预留
    % （每端口 ≥20 px，防止编译期自动增高），行距 = 行内最高模块 + 120。
    pos01 = [40 60 200 250];    pos02 = [620 60 780 170];    pos03 = [1200 60 1360 290];
    pos04 = [1780 60 1940 150]; pos05 = [40 410 200 600];    pos06 = [620 410 780 620];
    pos14 = [1200 410 1360 620]; pos08 = [1780 410 1940 500];
    pos09 = [40 740 200 830];   pos10 = [620 740 780 830];   pos11 = [1200 740 1360 830];
    pos12 = [1780 740 1940 830];
    pos13 = [40 950 200 1040];  pos15 = [620 950 780 1040];  pos07 = [1200 950 1360 1680];
    pos16 = [1780 950 1940 1340];

    buildScenarioManager(MDL, pos01);
    buildPropulsionController(MDL, pos02);
    buildPropulsionPlant(MDL, pos03);
    buildLoadMeasurement(MDL, pos04);
    buildEMSControllerC(MDL, pos05);
    buildGensetSystemE(MDL, pos06);
    model.build_pms_v2_e(MDL, pos07);     % 替换 Legacy_Commitment_Adapter（FR-449，T-007）
    model.build_safety_interlock_e(MDL, pos16); % 独立 Safety/Interlock 层（FR-444，T-007）
    buildBatteryConverter(MDL, pos14);
    buildUndervoltDerate(MDL, pos08);
    buildBusResidualMonitor(MDL, pos09);
    buildFuelConsumption(MDL, pos10);
    buildVoyageStop(MDL, pos11);
    buildDataLoggingDoc(MDL, pos12);
    buildDCBus(MDL, pos13);
    buildBusVoltageMonitor(MDL, pos15);
    add_block('simulink/Sources/Clock', [MDL '/t'], 'Position', [2260 60 2290 90]);

    %% ================= 3. 保存/重载（物化变体父级端口）后接线 =================
    save_system(MDL, mdlPath);
    close_system(MDL, 0);
    load_system(mdlPath);
    assignin('base', 'EMS_CTRL_LAW', 1);
    assignin('base', 'EMS_MODE', 1);
    % 清理变体父级掩码遗留端口（双保险）
    sys = [MDL '/05_EMS_Controller'];
    cleanupVariantPorts(sys, {'P_load_total_kW','SOC','v_cmd_mps','v_ship_mps','acceleration_mps2','x_ship_m','t'}, {'P_gen_ref_kW'});
    wireTopLevel(MDL);

    %% ================= 4. 信号记录配置 =================
    configureLogging(MDL);

    %% ================= 5. 保存并验证 =================
    save_system(MDL, mdlPath);
    % 注：law=7 内联图的权重/归一化常数经变体内 Constant 块以显式信号线接入
    % （绕开 R2026a Parameter 端口固化缺陷），下方 for-law update 循环即为编译验证。
    % law=4 Fixed ECMS（T-103）、law=5 SOC-Adaptive ECMS（T-105）、law=6 Oracle（T-106）、
    % law=7 NN-A-ECMS（T-204，Phase 2；Amendment v1.2 extrinsic）参数在 buildEMSControllerC 内已由
    % ecms2.ensure_bsfc_params / ecms2.ensure_nn_params 注入
    for law = [0 1 2 4 5 6 7]   % 无 law=3；4=EMS_Fixed_ECMS（T-103），5=EMS_SOC_Adaptive_ECMS（T-105），6=EMS_Oracle_ECMS（T-106），7=EMS_NN_AECMS（T-204）
        assignin('base', 'EMS_CTRL_LAW', law);
        assignin('base', 'EMS_MODE', double(law > 0));
        set_param(MDL, 'SimulationCommand', 'update');
        fprintf('[10] 更新图 (EMS_CTRL_LAW=%d) 成功\n', law);
    end

    %% ================= 6. 顶层布局收尾（2026-10-15 From/Goto 重构配套） =================
    % 编译后子系统端口实际坐标已定：按端口 y 对齐 From/Goto/Terminator，
    % 模块内信号线正交化（Simulink.BlockDiagram.route），隐藏顶层线名（tag 已可见）
    layoutTopLevel(MDL);
    save_system(MDL, mdlPath);
    fprintf('[10] 模型构建完成: %s\n', mdlPath);

catch err
    fprintf('[10] 构建失败: %s\n', err.message);
    for k = 1:numel(err.stack)
        fprintf('    at %s line %d\n', err.stack(k).name, err.stack(k).line);
    end
    if bdIsLoaded(MDL), close_system(MDL, 0); end
    rethrow(err);
end

%% ================= 6. 参数审计 CSV =================
if ~exist(fullfile(ROOT, 'reports'), 'dir'), mkdir(fullfile(ROOT, 'reports')); end
model.write_param_csv(fullfile(ROOT, 'reports', 'parameter_audit.csv'));

%% ========================================================================
%  以下为构建辅助函数
% ========================================================================

end

function buildScenarioManager(mdl, pos)
% 01_Operator_Interface（Phase 4-B T-006 改组，FR-428）：既有航次/环境输出不变 + 新增
%   驾驶意图输出 {ctrl_mode(Out7), v_ref_mps(Out1 改名), manual_power_cmd_pct(Out8)}
%   ctrl_mode = VOYAGE_CTRL_MODE 编译期求值（0=AUTO 1=MANUAL，工况内固定）；
%   manual_power_cmd_pct 经 From Workspace VOYAGE_MANUAL_CMD_TS 注入（Interpolate off，
%   支持 M1/M2/M3 序列）；既有输出端口序号 1~6 保持（接线稳定性）。
    sys = [mdl '/01_Operator_Interface'];
    add_block('simulink/Ports & Subsystems/Subsystem', sys, 'Position', pos);
    delete_block([sys '/In1']); delete_block([sys '/Out1']);
    add_block('simulink/Sources/In1', [sys '/x_ship_m'], 'Position', [20 80 50 110]);
    outs = {'v_ref_mps','v_current_mps','resistance_multiplier','P_hotel_kW','scenario_id','water_depth_m', ...
        'ctrl_mode','manual_power_cmd_pct'};
    for k = 1:numel(outs)
        add_block('simulink/Sinks/Out1', [sys '/' outs{k}], 'Position', [430 30+50*(k-1) 460 60+50*(k-1)]);
    end
    % 目标航速剖面（T-101）：距离节点（既有）+ 时间序列表（S20，design §2.1）
    %   speed_profile_mode='time' 时函数按 SCN.v_time_s/v_value_mps 时间节点分段恒定
    %   （等效 1-D Lookup on t），过渡由下游 Rate Limiter 平滑；既有场景 mode=0 路径不变。
    %   T-201 注入改造：时间表 Constant 块改读 base 变量 VOYAGE_*（仿真编译期求值，
    %   Simulink.SimulationInput.setVariable 可逐航次注入；默认值=S20，见 Model_Scenarios.m），
    %   避免为每个生成航次重建模型（200 航次 x 2 min 不可接受）。
    fnv = [sys '/v_cmd_profile'];
    add_block('simulink/User-Defined Functions/MATLAB Function', fnv, 'Position', [30 30 130 80]);
    setMFCode(fnv, CODE_VPROFILE, {});
    add_block('simulink/Sources/Clock', [sys '/t_clock'], 'Position', [20 250 50 270]);
    vconsts = {'kx','SCN.v_knots_x'; 'kv','SCN.v_knots_v'; 'vdef','SCN.target_speed_mps'; ...
        'tt','VOYAGE_V_TIME_S'; ...
        'tv','VOYAGE_V_VALUE_MPS'; ...
        'vmode','VOYAGE_SPEED_MODE'};
    vports = [4 5 6 7 8 3];   % 函数签名端口顺序: 1=x 2=t 3=mode 4=kx 5=kv 6=v_def 7=tt 8=tv
    add_line(sys, 'x_ship_m/1', 'v_cmd_profile/1');
    add_line(sys, 't_clock/1', 'v_cmd_profile/2');
    for k = 1:size(vconsts, 1)
        add_block('simulink/Sources/Constant', [sys '/CV_' vconsts{k,1}], ...
            'Position', [20 90+40*(k-1) 60 110+40*(k-1)], 'Value', vconsts{k,2});
        add_line(sys, ['CV_' vconsts{k,1} '/1'], ['v_cmd_profile/' num2str(vports(k))]);
    end
    add_block('simulink/Discontinuities/Rate Limiter', [sys '/v_cmd ramp'], 'Position', [150 30 240 60], ...
        'RisingSlewLimit', 'SCN.accel_ramp_mps2', 'FallingSlewLimit', '-SCN.decel_ramp_mps2', ...
        'InitialCondition', '0');
    add_line(sys, 'v_cmd_profile/1', 'v_cmd ramp/1');
    add_line(sys, 'v_cmd ramp/1', 'v_ref_mps/1');
    % 水流（T-101）：距离节点（既有）+ 时间序列表（S20 段 9 逆水 -1 m/s，其余 0）
    fnc = [sys '/current_profile'];
    add_block('simulink/User-Defined Functions/MATLAB Function', fnc, 'Position', [200 240 320 300]);
    setMFCode(fnc, CODE_CURRENT, {});
    cconsts = {'ckx','SCN.current_knots_x'; 'ckv','SCN.current_knots_v'; 'cdef','SCN.river_current_mps'; ...
        'ctt','VOYAGE_CURRENT_TIME_S'; ...
        'ctv','VOYAGE_CURRENT_VALUE_MPS'; ...
        'cvmode','VOYAGE_CURRENT_MODE'};
    cports = [4 5 6 7 8 3];   % 函数签名端口顺序: 1=x 2=t 3=mode 4=ckx 5=ckv 6=cdef 7=ctt 8=ctv
    add_line(sys, 'x_ship_m/1', 'current_profile/1');
    add_line(sys, 't_clock/1', 'current_profile/2');
    for k = 1:size(cconsts, 1)
        add_block('simulink/Sources/Constant', [sys '/CC_' cconsts{k,1}], ...
            'Position', [150 260+40*(k-1) 190 280+40*(k-1)], 'Value', cconsts{k,2});
        add_line(sys, ['CC_' cconsts{k,1} '/1'], ['current_profile/' num2str(cports(k))]);
    end
    add_line(sys, 'current_profile/1', 'v_current_mps/1');
    % 阻力剖面（MATLAB Function，距离触发）
    fn = [sys '/resist_profile'];
    add_block('simulink/User-Defined Functions/MATLAB Function', fn, 'Position', [200 90 320 190]);
    setMFCode(fn, CODE_RESIST, {});
    consts = {'profile','SCN.profile_code'; 'pos','SCN.resistance_change_position_m'; ...
        'amp','SCN.resistance_change_amplitude'; 'rampT','SCN.resistance_change_ramp_time_s'; ...
        'bands','SCN.resistance_bands'};
    for k = 1:size(consts, 1)
        add_block('simulink/Sources/Constant', [sys '/C_' consts{k,1}], ...
            'Position', [150 100+45*(k-1) 190 120+45*(k-1)], 'Value', consts{k,2});
        add_line(sys, ['C_' consts{k,1} '/1'], ['resist_profile/' num2str(k+1)]);
    end
    add_block('simulink/Sources/Constant', [sys '/C_vtarget'], 'Position', [150 220 190 240], 'Value', 'SCN.target_speed_mps');
    add_line(sys, 'x_ship_m/1', 'resist_profile/1');
    add_line(sys, 'C_vtarget/1', 'resist_profile/7');
    add_line(sys, 'resist_profile/1', 'resistance_multiplier/1');
    % 日用负荷与工况号
    add_block('simulink/Sources/Constant', [sys '/Hotel'], 'Position', [30 150 100 180], ...
        'Value', 'SCN.hotel_kW');
    add_line(sys, 'Hotel/1', 'P_hotel_kW/1');
    add_block('simulink/Sources/Constant', [sys '/ScenID'], 'Position', [30 200 100 230], ...
        'Value', 'SCN.id');
    add_line(sys, 'ScenID/1', 'scenario_id/1');
    % 水深环境输入（Model E T-003，FR-414）：VOYAGE_WATER_DEPTH_M 编译期求值
    % （Simulink.SimulationInput.setVariable 可逐航次注入；默认 20 m 深水渐近，
    %  见 ModelE_TestScenarios.m）。浅滩语义由 water_depth 表达（res_mult 浅滩语义退役）；
    %  不改名为 Environment_Input（D-7：C 包才重构工况语义）。
    add_block('simulink/Sources/Constant', [sys '/C_water_depth'], 'Position', [30 250 100 280], ...
        'Value', 'VOYAGE_WATER_DEPTH_M');
    add_line(sys, 'C_water_depth/1', 'water_depth_m/1');
    % 驾驶意图（T-006, FR-428）：ctrl_mode 编译期常量 + MANUAL 归一化指令表
    add_block('simulink/Sources/Constant', [sys '/C_ctrl_mode'], 'Position', [30 300 100 330], ...
        'Value', 'VOYAGE_CTRL_MODE');
    add_line(sys, 'C_ctrl_mode/1', 'ctrl_mode/1');
    add_block('simulink/Sources/From Workspace', [sys '/manual_cmd_src'], 'Position', [20 340 95 365], ...
        'VariableName', 'VOYAGE_MANUAL_CMD_TS', 'SampleTime', '0.01', 'Interpolate', 'off', ...
        'OutputAfterFinalValue', 'HoldingFinalValue');   % ZOH：禁线性插值（cmd 类通道同 GEN_CMD_STOP_TS 教训）
    add_line(sys, 'manual_cmd_src/1', 'manual_power_cmd_pct/1');
end

function buildPropulsionController(mdl, pos)
% 02_Propulsion_Controller（Phase 4-B T-006 改组，FR-429）：AUTO 速度 PI 原样保留（AC-416
%   行为不变仅指本条）；新增 MANUAL 路径（归一化线性映射 × Mot_P_nom → command-side
%   Rate Limiter 140 kW/s）→ Switch（ctrl_mode 编译期选路）→ 同一 Saturation →
%   唯一输出 P_prop_demand_kW；禁止新建 RPM 环/torque 域接口。
    sys = [mdl '/02_Propulsion_Controller'];
    add_block('simulink/Ports & Subsystems/Subsystem', sys, 'Position', pos);
    delete_block([sys '/In1']); delete_block([sys '/Out1']);
    add_block('simulink/Sources/In1', [sys '/v_ref_mps'], 'Position', [20 60 50 90]);
    add_block('simulink/Sources/In1', [sys '/v_ship_mps'], 'Position', [20 110 50 140]);
    add_block('simulink/Sources/In1', [sys '/ctrl_mode'], 'Position', [20 300 50 330]);
    add_block('simulink/Sources/In1', [sys '/manual_power_cmd_pct'], 'Position', [20 350 50 380]);
    add_block('simulink/Sinks/Out1', [sys '/P_prop_demand_kW'], 'Position', [330 80 360 110]);
    add_block('simulink/Math Operations/Sum', [sys '/err'], 'Position', [90 80 120 120], 'Inputs', '+-');
    add_line(sys, 'v_ref_mps/1', 'err/1');
    add_line(sys, 'v_ship_mps/1', 'err/2');
    add_block('simulink/Math Operations/Gain', [sys '/Kp'], 'Position', [150 60 190 90], 'Gain', 'ASSUMED_SpeedPI_Kp');
    add_block('simulink/Continuous/Integrator', [sys '/Ki_int'], 'Position', [150 120 190 160], ...
        'InitialCondition', '0', 'LimitOutput', 'on', ...
        'UpperSaturationLimit', 'Mot_P_nom/ASSUMED_SpeedPI_Ki', ...
        'LowerSaturationLimit', '0');
    add_line(sys, 'err/1', 'Kp/1');
    add_line(sys, 'err/1', 'Ki_int/1');
    add_block('simulink/Math Operations/Gain', [sys '/Ki'], 'Position', [230 130 270 160], 'Gain', 'ASSUMED_SpeedPI_Ki');
    add_line(sys, 'Ki_int/1', 'Ki/1');
    add_block('simulink/Math Operations/Sum', [sys '/PI out'], 'Position', [250 70 280 110], 'Inputs', '++');
    add_line(sys, 'Kp/1', 'PI out/1');
    add_line(sys, 'Ki/1', 'PI out/2');
    % MANUAL 路径（线性映射 × Mot_P_nom → command-side rate limiter，与 DG 20 kW/s 独立）
    add_block('simulink/Math Operations/Gain', [sys '/manual_gain'], 'Position', [150 340 200 370], 'Gain', 'Mot_P_nom');
    add_block('simulink/Discontinuities/Rate Limiter', [sys '/manual_cmd_ramp'], 'Position', [220 340 260 370], ...
        'RisingSlewLimit', 'Manual_Cmd_RateLimit_kW_per_s', 'FallingSlewLimit', '-Manual_Cmd_RateLimit_kW_per_s', ...
        'InitialCondition', '0');
    addL(sys, 'manual_power_cmd_pct', 1, 'manual_gain', 1);
    addL(sys, 'manual_gain', 1, 'manual_cmd_ramp', 1);
    % 模式选路（编译期）：Switch criteria u2>=0.5 满足走输入 1（MANUAL）、否则输入 3（AUTO PI）；
    % 两路径汇聚后过同一 Saturation → 唯一输出（design §5.2）
    add_block('simulink/Signal Routing/Switch', [sys '/mode_switch'], 'Position', [290 90 320 170], ...
        'Criteria', 'u2 >= Threshold', 'Threshold', '0.5');
    addL(sys, 'manual_cmd_ramp', 1, 'mode_switch', 1); % MANUAL（ctrl_mode>=0.5）
    addL(sys, 'ctrl_mode', 1, 'mode_switch', 2);
    addL(sys, 'PI out', 1, 'mode_switch', 3);          % AUTO（ctrl_mode<0.5）
    add_block('simulink/Discontinuities/Saturation', [sys '/Limit'], 'Position', [300 80 320 110], ...
        'UpperLimit', 'Mot_P_nom', 'LowerLimit', '0');
    add_line(sys, 'mode_switch/1', 'Limit/1');
    add_line(sys, 'Limit/1', 'P_prop_demand_kW/1');
end

function buildPropulsionPlant(mdl, pos)
% 03_Propulsion_Plant: 功率限幅->驱动滞后->转矩->齿轮箱->轴系->螺旋桨->船体
    sys = [mdl '/03_Propulsion_Plant'];
    add_block('simulink/Ports & Subsystems/Subsystem', sys, 'Position', pos);
    delete_block([sys '/In1']); delete_block([sys '/Out1']);
    ins = {'P_prop_demand_kW','P_prop_limit_kW','v_current_mps','resistance_multiplier','water_depth_m'};
    for k = 1:numel(ins)
        add_block('simulink/Sources/In1', [sys '/' ins{k}], 'Position', [15 30+45*(k-1) 45 60+45*(k-1)]);
    end
    outs = {'P_prop_actual_kW','v_ship_mps','x_ship_m','acceleration_mps2','R_hull_N','F_prop_eff_N','n_prop_rpm', ...
        'R_shallow_N','HT_ratio','domain_warning'};
    for k = 1:numel(outs)
        add_block('simulink/Sinks/Out1', [sys '/' outs{k}], 'Position', [720 20+45*(k-1) 750 50+45*(k-1)]);
    end
    % 可用功率限幅: P_prop_ref = min(demand, limit)
    add_block('simulink/Math Operations/MinMax', [sys '/Avail'], 'Position', [70 30 110 60], 'Function', 'min', 'Inputs', '2');
    add_line(sys, 'P_prop_demand_kW/1', 'Avail/1');
    add_line(sys, 'P_prop_limit_kW/1', 'Avail/2');
    % 驱动滞后 -> P_prop_actual
