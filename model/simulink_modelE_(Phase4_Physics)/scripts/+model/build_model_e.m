        'persistent ev_active ev_immediate ev_tFire ev_tPeakAbs ev_dP lastT\n' ...
        'if isempty(ev_active)\n' ...
        '    ev_active = false; ev_immediate = false;\n' ...
        '    ev_tFire = 0; ev_tPeakAbs = 0; ev_dP = 0;\n' ...
