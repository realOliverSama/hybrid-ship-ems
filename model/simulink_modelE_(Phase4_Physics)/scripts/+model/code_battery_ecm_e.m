function c = code_battery_ecm_e()
% CODE_BATTERY_ECM_E 返回 14_Battery_Converter/BatteryECM 的 MATLAB Function block 源码
%   （链 C T-008/T-009：LFP 1RC 等效电路 + SOP 四约束；design §4.5/§4.6 + OQ-9）
%   产物经 build_model_e.m 的 setMFCode 写入 block（全部 20 个入参按签名均为
%   block 输入端口，setMFCode 无需 Parameter 声明）；测试侧由 test_battery_ecm.m
%   将本字符串落盘 tempdir 直调，保证被测代码 = block 代码。
%   SOP 段为 +model/battery_sop_limits.m 函数体的逐字内联（修改须同步）。

lines = {
'function [P_bat_bus_kW, SOC_out, V_bat_V, I_bat_A, dSOC_dt, ...'
'          P_dis_avail_kW, P_chg_avail_kW, battery_power_limited, ...'
'          battery_discriminant_limit, ecm_lut_boundary_flag] = BatteryECM(...'
'    P_droop_kW, SOC, dt, ...'
'    Bat_SOC_LUT_nodes, Bat_OCV_LUT_V, Bat_R0_LUT_ohm, Bat_R1_LUT_ohm, Bat_C1_LUT_F, ...'
'    Bat_R0_chg_mult, Bat_eta_coul, Bat_Q_nom_Ah, Bat_V_min_V, Bat_V_max_V, ...'
'    Bat_I_limit_surrogate_A, Bat_P_conv_bus_max_kW, eta_dcdc, ...'
'    SOC_min, SOC_max, SOC_DisDerate_Start, SOC_ChgDerate_Start)'
'%#codegen'
'% BatteryECM — LFP 1RC 等效电路模型 + SOP 四约束（T-008/T-009 链 C）'
'% design.md §4.5/§4.6 + OQ-9 冻结项；0.01 s 离散步进（与模型 fixed-step 一致）。'
'% 符号约定（FR-423）：I > 0 = 放电，P_bat_bus_kW > 0 = 向母线放电。'
'% E = OCV - V_1 与 V_1 均为状态量估计，无代数环（NFR-409）。'
'% dSOC_dt 交外部 Integrator（限幅 [SOC_min, SOC_max] = [0.10, 0.95]）。'
'% Bat_eta_coul 仅进 SOC 电荷计量，不乘端口功率（Q5 红线，避免 double-count）；'
'% ASSUMED_Bat_Eff_* 与本块无关（仅 ECMS k_eq 内部口径）。'
''
'persistent V_1'
'if isempty(V_1)'
'    V_1 = 0;    % 极化电压初值 [V]（isempty 初始化）'
'end'
''
'% ---- 1) SOC-LUT（linear 插值 + 域外 clamp，禁止外推；九节点冻结事实源）----'
'soc_lut = min(max(SOC, Bat_SOC_LUT_nodes(1)), Bat_SOC_LUT_nodes(end));'
'if SOC > Bat_SOC_LUT_nodes(end)'
'    ecm_lut_boundary_flag = 1;    % SOC ∈ (0.9, 0.95]：用 0.9 节点值'
'else'
'    ecm_lut_boundary_flag = 0;'
'end'
'OCV = interp1(Bat_SOC_LUT_nodes, Bat_OCV_LUT_V, soc_lut, ''linear'');'
'R_0 = interp1(Bat_SOC_LUT_nodes, Bat_R0_LUT_ohm, soc_lut, ''linear'');'
'R_1 = interp1(Bat_SOC_LUT_nodes, Bat_R1_LUT_ohm, soc_lut, ''linear'');'
'C_1 = interp1(Bat_SOC_LUT_nodes, Bat_C1_LUT_F, soc_lut, ''linear'');'
''
'% ---- 2) SOP 四约束（内联自 +model/battery_sop_limits.m，保持一致）----'
'% 本地映射：OCV_V=OCV（LUT）、V1_V=V_1（persistent 预更新值）、'
'% [T-013 裁决 2026-09-04] 充放电共用 R_0(SOC)：charging gain ×1.15 无具体文献/实验'
'% 支撑（顾问表 v1 仅表注一行，Tran 2021 HPPC 未单列充电拟合），暂不人为引入；'
'% Bat_R0_chg_mult 置 1.0，待真实 BMS 数据后重评。 R0_chg_ohm = R_0 * Bat_R0_chg_mult;'
'OCV_V = OCV;'
'V1_V = V_1;'
'R0_dis_ohm = R_0;'
'R0_chg_ohm = R_0 * Bat_R0_chg_mult;'
''
'% ---- V_oc_est：状态量开路估计（OCV 与 V1 均为状态量，无代数依赖；OQ-9 语义）----'
'V_oc_est = OCV_V - V1_V;'
''
'% ---- 约束 1：P_current（电流 surrogate 上限，bus-side，design §4.6 原式）----'
'P_current_dis = Bat_I_limit_surrogate_A * V_oc_est / eta_dcdc / 1000;   % kW'
'P_current_chg = Bat_I_limit_surrogate_A * V_oc_est * eta_dcdc / 1000;   % kW'
''
'% ---- 约束 2：P_voltage（端子电压边界反解电流上限，bus-side）----'
'% 放电：V_t >= V_min 反解 I 上限；端子电压取 max(V_t, V_min) 保证不跌破 V_min'
'I_vmax = max(V_oc_est - Bat_V_min_V, 0) / max(R0_dis_ohm, 1e-12);'
'V_t_dis_lim = max(V_oc_est - I_vmax * R0_dis_ohm, Bat_V_min_V);'
'P_voltage_dis = I_vmax * V_t_dis_lim / eta_dcdc / 1000;                 % kW'
'% 充电：V_t <= V_max 反解电流上限（I_vmin <= 0）；V_oc_est >= V_max 时 I_vmin=0'
'% （P_chg=0：开路估计已到上限，不再允许充电）'
'I_vmin = -max(Bat_V_max_V - V_oc_est, 0) / max(R0_chg_ohm, 1e-12);      % <= 0'
'V_t_chg_lim = min(V_oc_est - I_vmin * R0_chg_ohm, Bat_V_max_V);'
'P_voltage_chg = max(abs(I_vmin) * V_t_chg_lim * eta_dcdc / 1000, 0);    % kW，clamp >= 0'
''
'% ---- 约束 3：P_SOC（沿用现有降额族；满刻度 = Bat_P_conv_bus_max_kW）----'
'% 放电：SOC <= DisDerate_Start(0.25) 线性降额 -> SOC_min(0.10) 归零'
'if SOC <= SOC_min'
'    P_soc_dis = 0;'
'    soc_derate_dis = 1;'
'elseif SOC <= SOC_DisDerate_Start'
'    P_soc_dis = Bat_P_conv_bus_max_kW * (SOC - SOC_min) / ...'
'        (SOC_DisDerate_Start - SOC_min);'
'    soc_derate_dis = 1;'
'else'
'    P_soc_dis = Bat_P_conv_bus_max_kW;    % 降额带外：非绑定（与约束 4 同值）'
'    soc_derate_dis = 0;'
'end'
'% 充电：SOC >= ChgDerate_Start(0.90) 线性降额 -> SOC_max(0.95) 归零'
'if SOC >= SOC_max'
'    P_soc_chg = 0;'
'    soc_derate_chg = 1;'
'elseif SOC >= SOC_ChgDerate_Start'
'    P_soc_chg = Bat_P_conv_bus_max_kW * (SOC_max - SOC) / ...'
'        (SOC_max - SOC_ChgDerate_Start);'
'    soc_derate_chg = 1;'
'else'
'    P_soc_chg = Bat_P_conv_bus_max_kW;    % 降额带外：非绑定（与约束 4 同值）'
'    soc_derate_chg = 0;'
'end'
''
'% ---- 约束 4：P_converter（DC/DC 母线侧图纸额定，bus-side；OQ-9 冻结）----'
'P_converter = Bat_P_conv_bus_max_kW;'
''
'% ---- 四约束取最小（可用功率非负：防退化状态产生负可用功率）----'
'P_dis_bus_kW = max(min(min(P_current_dis, P_voltage_dis), ...'
'    min(P_soc_dis, P_converter)), 0);'
'P_chg_bus_kW = max(min(min(P_current_chg, P_voltage_chg), ...'
'    min(P_soc_chg, P_converter)), 0);'
''
'flags = struct(''soc_derate_dis'', soc_derate_dis, ''soc_derate_chg'', soc_derate_chg);'
''
'P_dis_avail_kW = P_dis_bus_kW;'
'P_chg_avail_kW = P_chg_bus_kW;'
''
'% ---- 3) droop 请求 clamp（bus-side；SOP 上/下界，取代旧 lo_clamp/hi_clamp）----'
'P_bus_kW = min(max(P_droop_kW, -P_chg_avail_kW), P_dis_avail_kW);'
''
'% ---- 4) 端子换算（方向感知 DC/DC 效率；×1000 转 W；OQ-9：1050 kW = bus-side）----'
'if P_bus_kW > 0'
'    P_t_W = P_bus_kW * 1000 / eta_dcdc;    % 放电：P_t = P_bus/eta'
'else'
'    P_t_W = P_bus_kW * 1000 * eta_dcdc;    % 充电：P_t = P_bus*eta'
'end'
''
'% ---- 5) 方向感知 R_0（HPPC surrogate：充电方向内阻 ×Bat_R0_chg_mult）----'
'if P_t_W >= 0'
'    R0_eff = R_0;'
'else'
'    R0_eff = R_0 * Bat_R0_chg_mult;'
'end'
''
'% ---- 6) 解析求 I（OQ-9 二次式数值稳定形式，无迭代、无代数环）----'
'battery_power_limited = 0;'
'battery_discriminant_limit = 0;'
'E_oc = OCV - V_1;'
'if E_oc < 1e-3'
'    % NaN/Inf 防护：E 退化（≈0）→ 走 D<0 power-limit 分支语义'
'    P_t_act_W = E_oc^2 / (4 * R0_eff);'
'    I = E_oc / (2 * R0_eff);'
'    battery_power_limited = 1;'
'    battery_discriminant_limit = 1;'
'else'
'    D = E_oc^2 - 4 * R0_eff * P_t_W;'
'    if D >= 0'
'        % 小电流物理根（数值稳定形式，避免 E-sqrt(D) 大数相减）'
'        P_t_act_W = P_t_W;'
'        I = 2 * P_t_W / (E_oc + sqrt(D));'
'    else'
'        % 判别式 < 0：请求超过 ECM 状态物理极限 P_max_R = E^2/(4*R0)'
'        % （power-limit semantics：取 P_actual = P_max_R 重算电流；'
'        %   D_act = E^2 - 4*R0*P_max_R = 0 → I = 2*P_max_R/E = E/(2*R0)）'
'        P_t_act_W = E_oc^2 / (4 * R0_eff);'
'        I = E_oc / (2 * R0_eff);'
'        battery_power_limited = 1;'
'        battery_discriminant_limit = 1;'
'    end'
'end'
''
'% ---- 7) 端电压 V_t（= V_bat 输出；用预更新 V_1，状态语义）----'
'V_t = OCV - I * R0_eff - V_1;'
''
'% ---- 8) 极化状态 Euler 步进（persistent；0.01 s 离散，供下一步使用）----'
'V_1 = V_1 + dt * (-V_1 / (R_1 * C_1) + I / C_1);'
''
'% ---- 9) SOC 电荷积分速率（输出给外部 Integrator；eta_coul 仅进 SOC 计量）----'
'% 放电：dSOC = -I*dt/Q_nom；充电：dSOC = -eta_coul*I*dt/Q_nom（I<0 为正，入账打折）'
'if I >= 0'
'    dSOC_dt = -I / (3600 * Bat_Q_nom_Ah);'
'else'
'    dSOC_dt = -Bat_eta_coul * I / (3600 * Bat_Q_nom_Ah);'
'end'
''
'% ---- 10) 实际端口功率输出（clamp 后再经 D<0 修正的值）----'
'if battery_power_limited == 1'
'    % D<0 仅可能发生在放电方向（充电时 D = E^2 + 4*R0*|P_t| > 0 恒成立）；'
'    % E 退化防护分支的 P_t_act >= 0 亦按放电口径反算 bus-side'
'    P_bat_bus_kW = P_t_act_W * eta_dcdc / 1000;'
'else'
'    P_bat_bus_kW = P_bus_kW;    % 请求经 SOP clamp 后被 ECM 完全满足'
'end'
'SOC_out = SOC;'
'V_bat_V = V_t;'
'I_bat_A = I;'
'end'
};
c = strjoin(lines, newline);
end