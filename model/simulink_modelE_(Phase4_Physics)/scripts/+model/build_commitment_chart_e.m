function ch = build_commitment_chart_e(blockPath)
%BUILD_COMMITMENT_CHART_E 脚本化创建 DG_Commitment_Supervisor Stateflow chart（Model E, T-005）
%   model.build_commitment_chart_e(blockPath)
%   blockPath: 'model/xxx' 或 'model/xxx/subsys/chart_block' —— 在该位置创建 sflib/Chart 块
%   并填充状态图/数据/迁移。builder（T-007 集成 07_PMS_v2）与 harness 单测
%   （tests/build_commitment_harness.m）共用本函数，保证两处图表逐位一致（幂等）。
%
%   依据：.specs/phase4-b-pms-safety design.md §5.4 + FR-436~440 + D-B5（并行计时）+
%   D-B7（仲裁顺序 veto>safety>normal 源码固化）。
%   纪律：
%   - 不用 after() 时序算子（design §5.4）：全部 timer 为显式整数 tick 计数器；
%   - 每调用 = 1 tick = 0.01 s（ChartUpdate=DISCRETE，SampleTime=0.01，OQ-6 同口径）；
%   - 状态图：ONE_DG_NORMAL(1) ⇄ DG2_START_PENDING(2) ⇄ TWO_DG_NORMAL(3)；
%   - 迁移优先级（同源迁移按优先级降序，= 仲裁顺序固化，FR-438/D-B7）：
%       fault veto（fault_latch，最高）> safety force（force_*_req）> normal（阈值+timer）；
%   - reason_code 枚举（design §5.4，1..7）：
%       1=NORMAL_HIGH_LOAD 2=NORMAL_LOW_LOAD 3=SAFETY_DG_FAULT
%       4=SAFETY_REALIZED_SUPPLY_DEFICIT 5=SAFETY_PROSPECTIVE_FIRM_CAPACITY_DEFICIT
%       6=SAFETY_MIN_GEN_SURPLUS 7=FORCED（DD-8 bench force 通道专用：正常 Gate 中出现即
%       FAIL，兼作 44 号负向验证向量——正常 chart 路径永不产生 7）；
%   - timer 饱和语义：start/stop/online 计数到各自阈值即封顶（design §6.3 饱和事件口径）；
%   - 并行计时（D-B5）：stop_hold 与 online 在 TWO_DG 内独立累计（AND 汇合于停机迁移），
%       最短 ON = 恰好 300 s；min_down=0：停机后无额外禁止期，start_hold 满足即可重启；
%   - aborted-start（A2 契约延续）：PENDING 期间负荷回落不撤启动指令（cmd_onoff_DG2 保持 1），
%       25+5 s 物理过程由 Plant 状态机负责；PENDING 仅在 state_DG2==ON 或 fault 时退出；
%   - 审计九元组（FR-440）：每次迁移在目标态 entry 记录
%       {old_state, new_state, reason_code, P_commit, start_hold, stop_hold, online,
%        safety_override}（timestamp 由 logsout 采样时刻给出，Gate 后处理拼接），
%       迁移后保持至下次迁移；
%   - cmd_onoff → Plant 映射（07_PMS_v2 输出级，集成契约）：
%       enable_i = cmd_onoff_i；cmd_stop_i = 1 − cmd_onoff_i（auto 模式）；
%       fault veto 经 cmd_onoff_i=0 同时实现"禁 START + 令 STOP"（GensetUnitE OFF 态
%       cmd_stop 优先语义天然阻断重启）。

if isempty(which('sflib')), error('build_commitment_chart_e: 需要 Stateflow'); end

% ---- 块存在性幂等：已存在则先删除（builder 重建流程整模型从零构建，此处兜底） ----
if ~isempty(find_system('SearchDepth', 3, 'Name', blockPath))
    delete_block(blockPath);
end
add_block('sflib/Chart', blockPath, 'Position', [40 40 320 220]);

rt = sfroot;
chArr = rt.find('-isa', 'Stateflow.Chart', 'Path', blockPath);
if numel(chArr) ~= 1
    error('build_commitment_chart_e: 未定位到 chart 对象 %s', blockPath);
end
ch = chArr(1);
ch.Name = 'PMS_Commitment_Supervisor';
ch.ChartUpdate = 'DISCRETE';        % persistent 状态块离散化（R2026a 纪律，NFR-415）
ch.SampleTime = '0.01';
ch.ActionLanguage = 'MATLAB';

% ================= 数据（签名即契约） =================
% 输入（Scope=Input）
inNames = {'P_commit_kW', 'state_DG2', 'fault_latch_DG1', 'fault_latch_DG2', ...
    'force_start_dg2_req', 'force_start_reason', 'force_stop_dg2_req', 'force_stop_reason'};
% 输出（Scope=Output）
outNames = {'cmd_onoff_DG1', 'cmd_onoff_DG2', 'commitment_state', 'reason_code', ...
    'start_hold_timer', 'stop_hold_timer', 'online_timer', 'audit_valid', ...
    'audit_old_state', 'audit_new_state', 'audit_P_commit_kW', ...
    'audit_t_start_hold', 'audit_t_stop_hold', 'audit_t_online', 'audit_safety_override'};
% 局部（Scope=Local）
localNames = {'tr_reason', 'pending_reason'};
% 参数（Scope=Parameter，base workspace 由 ModelE_Control_Parameters.m 提供，FR-451）
paramNames = {'PMS_start_threshold_kW', 'PMS_stop_threshold_kW', ...
    'T_start_hold_ticks', 'T_stop_hold_ticks', 'PMS_min_up_ticks'};

mkData = @(scope, nm) dealData(ch, scope, nm);
for k = 1:numel(inNames),  mkData('Input',     inNames{k});  end
for k = 1:numel(outNames), mkData('Output',    outNames{k}); end
for k = 1:numel(localNames), mkData('Local',   localNames{k}); end
for k = 1:numel(paramNames), mkData('Parameter', paramNames{k}); end

% ================= 状态 =================
st1 = Stateflow.State(ch);
st1.LabelString = sprintf(['ONE_DG_NORMAL\n' ...
    'entry: if (commitment_state == 0)\n' ...
    '  commitment_state = 1;\n' ...
    '  reason_code = 0;\n' ...
    '  audit_valid = 0;\n' ...
    '  start_hold_timer = 0; stop_hold_timer = 0; online_timer = 0;\n' ...
    '  cmd_onoff_DG1 = double(fault_latch_DG1 < 0.5);\n' ...
    '  cmd_onoff_DG2 = 0;\n' ...
    'else\n' ...
    '  audit_old_state = commitment_state; audit_new_state = 1;\n' ...
    '  audit_P_commit_kW = P_commit_kW;\n' ...
    '  audit_t_start_hold = start_hold_timer; audit_t_stop_hold = stop_hold_timer;\n' ...
    '  audit_t_online = online_timer;\n' ...
    '  audit_safety_override = double(tr_reason >= 3);\n' ...
    '  audit_valid = 1;\n' ...
    '  reason_code = tr_reason;\n' ...
    '  commitment_state = 1;\n' ...
    '  start_hold_timer = 0; stop_hold_timer = 0; online_timer = 0;\n' ...
    '  cmd_onoff_DG1 = double(fault_latch_DG1 < 0.5);\n' ...
    '  cmd_onoff_DG2 = 0;\n' ...
    'end\n' ...
    'during: cmd_onoff_DG1 = double(fault_latch_DG1 < 0.5);\n' ...
    '  cmd_onoff_DG2 = 0;\n' ...
    '  stop_hold_timer = 0; online_timer = 0;\n' ...
    '  if (P_commit_kW > PMS_start_threshold_kW)\n' ...
    '    start_hold_timer = min(start_hold_timer + 1, T_start_hold_ticks);\n' ...
    '  else\n' ...
    '    start_hold_timer = 0;\n' ...
    '  end']);
st1.Position = [40 40 260 120];

st2 = Stateflow.State(ch);
st2.LabelString = sprintf(['DG2_START_PENDING\n' ...
    'entry: audit_old_state = commitment_state; audit_new_state = 2;\n' ...
    '  audit_P_commit_kW = P_commit_kW;\n' ...
    '  audit_t_start_hold = start_hold_timer; audit_t_stop_hold = stop_hold_timer;\n' ...
    '  audit_t_online = online_timer;\n' ...
    '  audit_safety_override = double(tr_reason >= 3);\n' ...
    '  audit_valid = 1;\n' ...
    '  reason_code = tr_reason; pending_reason = tr_reason;\n' ...
    '  commitment_state = 2;\n' ...
    '  start_hold_timer = 0; stop_hold_timer = 0; online_timer = 0;\n' ...
    '  cmd_onoff_DG1 = double(fault_latch_DG1 < 0.5);\n' ...
    '  cmd_onoff_DG2 = double(fault_latch_DG2 < 0.5);\n' ...
    'during: cmd_onoff_DG1 = double(fault_latch_DG1 < 0.5);\n' ...
    '  cmd_onoff_DG2 = double(fault_latch_DG2 < 0.5);\n' ...
    '  start_hold_timer = 0; stop_hold_timer = 0; online_timer = 0;\n' ...
    '  % PENDING 期间负荷回落不撤启动（aborted-start 契约：25+5 s 物理由 Plant 负责）']);
st2.Position = [360 40 260 120];

st3 = Stateflow.State(ch);
st3.LabelString = sprintf(['TWO_DG_NORMAL\n' ...
    'entry: audit_old_state = commitment_state; audit_new_state = 3;\n' ...
    '  audit_P_commit_kW = P_commit_kW;\n' ...
    '  audit_t_start_hold = start_hold_timer; audit_t_stop_hold = stop_hold_timer;\n' ...
    '  audit_t_online = online_timer;\n' ...
    '  audit_safety_override = double(tr_reason >= 3);\n' ...
    '  audit_valid = 1;\n' ...
    '  reason_code = tr_reason;\n' ...
    '  commitment_state = 3;\n' ...
    '  start_hold_timer = 0; stop_hold_timer = 0; online_timer = 0;\n' ...
    '  cmd_onoff_DG1 = double(fault_latch_DG1 < 0.5);\n' ...
    '  cmd_onoff_DG2 = double(fault_latch_DG2 < 0.5);\n' ...
    'during: cmd_onoff_DG1 = double(fault_latch_DG1 < 0.5);\n' ...
    '  cmd_onoff_DG2 = double(fault_latch_DG2 < 0.5);\n' ...
    '  start_hold_timer = 0;\n' ...
    '  if (P_commit_kW < PMS_stop_threshold_kW)\n' ...
    '    stop_hold_timer = min(stop_hold_timer + 1, T_stop_hold_ticks);\n' ...
    '  else\n' ...
    '    stop_hold_timer = 0;\n' ...
    '  end\n' ...
    '  if (state_DG2 == 3)\n' ...
    '    online_timer = min(online_timer + 1, PMS_min_up_ticks);\n' ...
    '  else\n' ...
    '    online_timer = 0;\n' ...
    '  end']);
st3.Position = [360 220 260 120];

% ================= 默认迁移 → ONE_DG_NORMAL =================
td = Stateflow.Transition(ch);
td.Destination = st1;
td.LabelString = '{tr_reason = 0;}';

% ================= 迁移（同源按优先级创建：fault > safety > normal，D-B7） ====
% --- FROM ONE_DG_NORMAL ---
% T1（safety force start，绕过 hold；目标机 healthy 由 16 号保证，此处再防御 fault）
t11 = Stateflow.Transition(ch);
t11.Source = st1; t11.Destination = st2;
t11.LabelString = '[force_start_dg2_req > 0.5 && fault_latch_DG2 < 0.5]{tr_reason = force_start_reason;}';

% T2（normal start：P_commit>425 持续 T_start_hold_ticks；fault veto 守卫——锁存机组禁启动，
%   否则故障后 P>425 会造成 1→2→1 振铃，FR-438 veto 最高优先级）
t12 = Stateflow.Transition(ch);
t12.Source = st1; t12.Destination = st2;
t12.LabelString = '[start_hold_timer >= T_start_hold_ticks && fault_latch_DG2 < 0.5]{tr_reason = 1;}';

% --- FROM DG2_START_PENDING ---
% T3（fault veto 最高：DG2 故障 → 撤销启动，回 ONE_DG）
t23 = Stateflow.Transition(ch);
t23.Source = st2; t23.Destination = st1;
t23.LabelString = '[fault_latch_DG2 > 0.5]{tr_reason = 3;}';

% T4（DG2 物理并网完成 → TWO_DG；reason 沿用启动时刻原因）
t24 = Stateflow.Transition(ch);
t24.Source = st2; t24.Destination = st3;
t24.LabelString = '[state_DG2 == 3]{tr_reason = pending_reason;}';

% --- FROM TWO_DG_NORMAL ---
% T5（fault veto 最高：DG2 故障丢失 → FORCE_STOP 语义回 ONE_DG）
t35 = Stateflow.Transition(ch);
t35.Source = st3; t35.Destination = st1;
t35.LabelString = '[fault_latch_DG2 > 0.5]{tr_reason = 3;}';

% T6（safety force stop：绕过 stop_hold/min_up）
t36 = Stateflow.Transition(ch);
t36.Source = st3; t36.Destination = st1;
t36.LabelString = '[force_stop_dg2_req > 0.5]{tr_reason = force_stop_reason;}';

% T7（normal stop：P_commit<350 持续 12000 tick ∧ online>=30000，AND 汇合）
t37 = Stateflow.Transition(ch);
t37.Source = st3; t37.Destination = st1;
t37.LabelString = '[P_commit_kW < PMS_stop_threshold_kW && stop_hold_timer >= T_stop_hold_ticks && online_timer >= PMS_min_up_ticks]{tr_reason = 2;}';

% 保存职责归调用方（harness 建临时模型后自行 save；T-007 builder 在构建流程内统一 save）
end

function dealData(ch, scope, nm)
% 创建 Stateflow.Data 并设作用域；全部数据为标量 double（显式 DataType+Size=1，
% 避免 R2026a "Inherit: Same as Simulink" 未定属性编译错误与维度传播歧义）。
% Local/Output 设初始值 0：迁移条件在首拍先于 during 读 timer（上一拍语义），
% 无初始值将触发 "在写入之前读取" 运行时违例。
d = Stateflow.Data(ch);
d.Name = nm;
d.Scope = scope;
d.DataType = 'double';
d.Props.Array.Size = '1';
if strcmp(scope, 'Output') || strcmp(scope, 'Local')
    d.Props.InitialValue = '0';
end
end