function c = code_hull_e()
% CODE_HULL_E —— Ship_Hull_Dynamics_E 块源码（T-004，design §4.1 公式链，FR-412~415）
% 供 builder 以 setMFCode(fn, model.code_hull_e(), {...}) 写入 MATLAB Function 块；
% 单元测试 test_hull_shallow.m 直接以本字符串写盘调用（测的代码 = 块的代码）。
% 参数清单（签名顺序，全部来自 ModelE_Physics_Parameters.m 单一事实源）：
%   Hull_K_R, Ship_Mass, Hull_Lpp_m, Hull_T_m, nu_water, Hull_k_form,
%   Shallow_c1, Shallow_c2, Shallow_c3, Shallow_HT_deep_limit, Shallow_HT_min_valid
% 注意：Δk 的 0.644 / -1.72 按任务书为块内字面量（来源注释见块内），
%   config 中的 Shallow_deltak_coef / Shallow_deltak_exp 不作为块参数传入。
c = sprintf([ ...
    'function [dVdt, R_total_N, R_shallow_N, HT_ratio, domain_warning] = ShipHullDynamicsE(...\n' ...
    '    V_ship, F_prop_eff, V_current, F_env, resistance_multiplier, water_depth_m, ...\n' ...
    '    Hull_K_R, Ship_Mass, Hull_Lpp_m, Hull_T_m, nu_water, Hull_k_form, ...\n' ...
    '    Shallow_c1, Shallow_c2, Shallow_c3, Shallow_HT_deep_limit, Shallow_HT_min_valid)\n' ...
    '%% Ship_Hull_Dynamics_E —— 船体纵向动力学 + 浅水相对增量阻力（design §4.1，FR-412~415，T-004）\n' ...
    '%% 相对增量法：文献公式只计算无量纲浅水增量 Δr(H/T, Re)，绝对阻力水平由 Hull_K_R 锚定\n' ...
    '%% 域处理（FR-415，禁静默外推）：\n' ...
    '%%   H/T > Shallow_HT_deep_limit(3.0) -> Δr = 0（深水渐近）\n' ...
    '%%   H/T < Shallow_HT_min_valid(1.2)  -> clamp 到 1.2 计算 + domain_warning = 1\n' ...
    '%%   其间正常计算，domain_warning = 0\n' ...
    '%% 数值稳健（NFR-411）：零速跳过浅水项（Re=0 -> log10 发散 -> 0/0 NaN），Re 下限保护 1e3，\n' ...
    '%%   全程无 NaN/Inf\n' ...
    '%% 已知局限（证据链登记）：c1/c2/c3 标定族 C_B=0.86 与本船 0.60 型差外推；\n' ...
    '%%   未含浅水兴波临界区（Fr_h->1）分量，由 H/T>=1.2 域限 + C 包 UKC 限速规避\n' ...
    'V_rel = V_ship - V_current;\n' ...
    'HT_ratio = water_depth_m / Hull_T_m;\n' ...
    'domain_warning = 0;\n' ...
    'HT_eff = HT_ratio;\n' ...
    'shallow_active = true;\n' ...
    'if HT_ratio > Shallow_HT_deep_limit\n' ...
    '    shallow_active = false;   %% 深水渐近：Δr = 0\n' ...
    'elseif HT_ratio < Shallow_HT_min_valid\n' ...
    '    HT_eff = Shallow_HT_min_valid;   %% clamp 到下界（禁静默外推）\n' ...
    '    domain_warning = 1;              %% MODEL_DOMAIN_WARNING（NFR-411）\n' ...
    'end\n' ...
    'if abs(V_rel) < eps\n' ...
    '    R_total_N = 0;\n' ...
    '    R_shallow_N = 0;\n' ...
    '    dVdt = (F_prop_eff + F_env) / Ship_Mass;\n' ...
    '    return;\n' ...
    'end\n' ...
    'R_deep = resistance_multiplier * Hull_K_R * V_rel * abs(V_rel);\n' ...
    'R_shallow_N = 0;\n' ...
    'if shallow_active\n' ...
    '    Re = max(abs(V_rel) * Hull_Lpp_m / nu_water, 1e3);   %% Re 下限保护（NFR-411）\n' ...
    '    Lr = log10(Re);\n' ...
    '    C_F = 0.075 / (Lr - 2)^2;                            %% ITTC-57 摩擦阻力系数\n' ...
    '    C_Fstar = 0.08468 / (Lr - 1.631)^2 * ...\n' ...
    '        (1 + Shallow_c1 / (Lr + Shallow_c2) * HT_eff^Shallow_c3);   %% Zhang/Rhine86 [1][3]\n' ...
    '    deltak = 0.644 * HT_eff^(-1.72);   %% Millward[4]/Zhang[1]：系数 0.644 与指数 -1.72 字面量\n' ...
    '    deltar = (1 + Hull_k_form + deltak) * C_Fstar / ((1 + Hull_k_form) * C_F) - 1;\n' ...
    '    R_shallow_N = R_deep * deltar;   %% Δr 为相对增量：R_shallow 是浅水附加量（FR-413）\n' ...
    'end\n' ...
    'R_total_N = R_deep + R_shallow_N;   %% = R_deep*(1+Δr)\n' ...
    'dVdt = (F_prop_eff - R_total_N + F_env) / Ship_Mass;\n' ...
    'end\n']);
end