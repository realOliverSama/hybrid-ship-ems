function c = code_wake_ht_e()
% CODE_WAKE_HT_E —— Wake_vs_HT 块源码（T-005，OQ-4/D-3，design §4.2）
% 供 builder 以 setMFCode(fn, model.code_wake_ht_e(), {...}) 写入 MATLAB Function 块；
% 输入 HT_ratio 必须接线 Ship_Hull_Dynamics_E 的 HT_ratio 输出（H/T 单一事实源，禁止两处各自计算）。
% 参数清单（签名顺序，全部来自 ModelE_Physics_Parameters.m 单一事实源）：
%   Wake_w_deep, Wake_HT_nodes, Wake_w_Zhang, Wake_HT_ref, Wake_w_ref
c = sprintf([ ...
    'function w = WakeVsHT(HT_ratio, Wake_w_deep, Wake_HT_nodes, Wake_w_Zhang, Wake_HT_ref, Wake_w_ref)\n' ...
    '%% Wake_vs_HT —— 伴流分数 w(H/T) = w_deep + Δw_Zhang(H/T)（OQ-4/D-3，design §4.2，T-005）\n' ...
    '%% 【transferred literature surrogate 声明】Δw 取自 Zhang 2023 双桨表（标定族 C_B=0.86 与\n' ...
    '%% 本船 C_B=0.60 不同），只借相对变化量；不得表述为本船验证伴流场。\n' ...
    '%% 深水锚 w_deep 由 Harvald/Molland 回归独立确定（D-3），非 Zhang 绝对值。\n' ...
    '%% 域处理（与船体模块 clamp 语义一致）：\n' ...
    '%%   H/T > Wake_HT_ref(2.7)      -> Δw = 0（深水渐近，显式分支，不依赖插值未定义行为）\n' ...
    '%%   H/T < min(Wake_HT_nodes)    -> clamp 到首节点 1.2（与船体模块 clamp 一致）\n' ...
    '%%   其间 linear 插值（防 overshoot），查询域 clamp [1.2, Wake_HT_ref]\n' ...
    'if HT_ratio > Wake_HT_ref\n' ...
    '    w = Wake_w_deep;   %% 深水渐近：Δw = 0\n' ...
    'else\n' ...
    '    wHT = min(max(HT_ratio, min(Wake_HT_nodes)), Wake_HT_ref);\n' ...
    '    w = Wake_w_deep + (interp1(Wake_HT_nodes, Wake_w_Zhang, wHT, ''linear'') - Wake_w_ref);\n' ...
    'end\n' ...
    'end\n']);
end