function c = code_propeller_e()
% CODE_PROPELLER_E —— Propeller_Hydrodynamics 块源码（T-005，FR-417/D-8）
% 与 legacy CODE_PROPELLER 完全同构；唯一差异：wake_fraction（Parameter）→ w_signal（输入信号）。
% 四个 K 已按 w_deep=0.10 在 ModelE_Physics_Parameters.m 重标定落盘（D-8），此处只引用不改值。
% 螺旋桨 D、K_T/K_Q、P/D 保持 INTENTIONALLY UNRESOLVED（FR-417），禁止填入任何借用值。
% 参数清单（签名顺序）：K_Fw, K_Fv, K_Qw, K_Qv
c = sprintf([ ...
    'function [F_prop_eff, Q_prop, P_hydro_kW, V_A] = PropellerHydroSimpleE(...\n' ...
    '    n_prop_rpm, V_ship_mps, V_current_mps, w_signal, K_Fw, K_Fv, K_Qw, K_Qv)\n' ...
    '%% 简化螺旋桨水动力模型（Model E，T-005：与 legacy PropellerHydroSimple 完全同构）\n' ...
    '%% 唯一差异：wake_fraction 由 Parameter 改为输入信号 w_signal（w(H/T) 来自 Wake_vs_HT）\n' ...
    '%% 螺旋桨 D、K_T/K_Q、P/D 保持 INTENTIONALLY UNRESOLVED（FR-417），不得填入借用值\n' ...
    'omega = n_prop_rpm * pi / 30;\n' ...
    'V_rel = V_ship_mps - V_current_mps;\n' ...
    'V_A = (1 - w_signal) * V_rel;\n' ...
    'F_prop_eff = K_Fw * omega * abs(omega) - K_Fv * V_A * abs(V_A);\n' ...
    'Q_prop = K_Qw * omega * abs(omega) - K_Qv * V_A * abs(V_A);\n' ...
    'P_hydro_kW = Q_prop * omega / 1000;\n' ...
    'end\n']);
end