function c = code_genset_unit_e()
%CODE_GENSENT_UNIT_E 返回 GensetUnitE MATLAB Function block 源码字符串（Model E，T-006）
%   c = model.code_genset_unit_e()
%   用途：builder 经 setMFCode 写入 06_Genset_System 内 DG1/DG2 两个 MATLAB Function 块
%   （同一代码、两个块实例，persistent 状态按块实例隔离）；
%   纯 MATLAB 单测（scripts/tests/test_genset_statemachine.m）亦以此字符串写盘直接调用。
%   依据：.specs/phase4-a2-model-e-construction/design.md §4.3 + OQ-6（定稿）；
%   D-4：min up/min_down time 不在本 Plant 内（unit commitment 属 B 包 PMS v2）；
%   参数事实源：config/ModelE_Physics_Parameters.m §5（数值冻结，禁止在此重议）。
%   采样约定：固定步 0.01 s，每步调用一次 = 1 tick；dt=0.01 硬编码于爬坡/惯性更新，
%   若模型固定步长变更，N_ticks_* 与该 dt 须一并重推（详见 chain_b_integration_notes.md）。

lines = { ...
'function [P_actual_kW, state, below_min_flag, start_count] = GensetUnitE(...'
'    cmd_start, cmd_stop, P_ref_kW, ...'
'    DG_P_rated_kW, DG_P_min_kW, DG_ramp_kW_per_s, DG_tau_s, ...'
'    N_ticks_starting, N_ticks_sync, N_ticks_cooldown, Pgen_init)'
'%#codegen'
'% GensetUnitE：单发电机组启停状态机 + 功率链（Model E, FR-418/419, OQ-6 定稿）'
'%   DG1/DG2 各用一个块实例（同一代码）；固定步 0.01 s，每步调用一次 = 1 tick；'
'%   状态驻留用整数 tick 计数做转移判据（OQ-6，禁止浮点时间比较）。'
'%   state: 0=OFF 1=STARTING 2=SYNCHRONIZING 3=ON 4=COOLDOWN（数值状态，供 fuel/log 用）'
'%   D-4：min up/min down time 不在本 Plant 内（unit commitment 属 B 包 PMS v2）；'
'%        COOLDOWN 物理驻留 N_ticks_cooldown 表达停机间隔，期间 cmd_start 忽略。'
'%   aborted-start：STARTING/SYNC 不可中断；cmd_stop 只置 pending_stop，进入 ON 后一拍内执行停机。'
'%   OFF 态 stop 优先（2026-09-04 主 Agent 裁决）：cmd_start=1 且 cmd_stop=1 时保持 OFF，防停机后无限再启动。'
'persistent st n_tick pending_stop n_starts P_ramp P_lag'
'if isempty(st)'
'    st = 0;                 % 初始 OFF（新状态机初始 OFF；Pgen_init 仅作 P_lag legacy 初值）'
'    n_tick = 0;             % 当前状态驻留 tick 计数'
'    pending_stop = false;   % STARTING/SYNC 期间登记的停机请求'
'    n_starts = 0;           % 完成启动次数（SYNC 完成时 +1，含 aborted-start）'
'    P_ramp = 0;             % 爬坡状态 [kW]'
'    P_lag = Pgen_init;      % 一阶惯性状态 [kW]（legacy 常开模型初值兼容语义）'
'end'
''
'P_actual_kW = 0;            % 非 ON 态恒 0；ON 态由功率链覆写'
'below_min_flag = 0;         % 仅 ON 态置位（ref < P_min；switch 后按最终状态统一判定）'
''
'switch st'
'    case 0 % OFF：cmd_start 触发启动（cmd_stop 有效时 stop 优先，防停机后无限再启动）'
'        if cmd_start > 0.5 && cmd_stop < 0.5'
'            st = 1;                  % OFF -> STARTING'
'            n_tick = 0;'
'            pending_stop = false;    % n_starts 不在此刻加（SYNC 完成时才计）'
'            P_ramp = 0;              % 启动从零爬坡'
'            P_lag = 0;'
'        end'
''
'    case 1 % STARTING：不可中断（aborted-start 只登记）'
'        n_tick = n_tick + 1;'
'        if cmd_stop > 0.5'
'            pending_stop = true;'
'        end'
'        if n_tick >= N_ticks_starting'
'            st = 2;                  % STARTING -> SYNCHRONIZING'
'            n_tick = 0;'
'        end'
''
'    case 2 % SYNCHRONIZING：不可中断'
'        n_tick = n_tick + 1;'
'        if cmd_stop > 0.5'
'            pending_stop = true;'
'        end'
'        if n_tick >= N_ticks_sync'
'            n_starts = n_starts + 1; % 启动完成（启动燃油由此计量一次）'
'            st = 3;                  % SYNCHRONIZING -> ON'
'            n_tick = 0;'
'        end'
''
'    case 3 % ON：功率链 + 停机命令（pending_stop 在此执行）'
'        if cmd_stop > 0.5 || pending_stop'
'            pending_stop = false;'
'            st = 4;                  % ON -> COOLDOWN（断路器分闸，本拍 P=0）'
'            n_tick = 0;'
'        else'
'            % ref clamp [P_min, rated]（below_min_flag 在 switch 后按最终状态统一置位）'
'            P_ref_c = min(max(P_ref_kW, DG_P_min_kW), DG_P_rated_kW);'
'            if P_ramp < P_ref_c'
'                P_ramp = min(P_ramp + DG_ramp_kW_per_s*0.01, P_ref_c);  % 爬坡限幅（0.01 s 步）'
'            elseif P_ramp > P_ref_c'
'                P_ramp = max(P_ramp - DG_ramp_kW_per_s*0.01, P_ref_c);'
'            end'
'            P_lag = P_lag + (P_ramp - P_lag)*0.01/DG_tau_s;             % 一阶惯性 tau'
'            P_actual_kW = min(max(P_lag, 0), DG_P_rated_kW);'
'            % 注：爬坡过渡期 P<P_min 为 registered 过渡（below_min_flag 登记；'
'            % 燃油侧按 clamp 到 BSFC 下节点(125)查表，见 FuelModelE）'
'        end'
''
'    case 4 % COOLDOWN：P=0；cmd_start 忽略（D-4：物理驻留表达最小停机间隔）'
'        n_tick = n_tick + 1;'
'        if n_tick >= N_ticks_cooldown'
'            st = 0;                  % COOLDOWN -> OFF'
'            n_tick = 0;'
'        end'
''
'    otherwise % 防御：非法状态归 OFF（无 NaN 路径）'
'        st = 0;'
'        n_tick = 0;'
'end'
''
'state = st;                  % 输出为本拍转移后的状态'
'if st == 3 && P_ref_kW < DG_P_min_kW'
'    below_min_flag = 1;      % 输出约定：flag=1 当且仅当 state==3 且 ref<P_min（含 ON 入口拍）'
'end'
'start_count = n_starts;'
'end'};
c = strjoin(lines, newline);
end