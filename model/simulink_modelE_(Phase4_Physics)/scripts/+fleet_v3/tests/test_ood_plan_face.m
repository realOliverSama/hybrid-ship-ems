function ok = test_ood_plan_face()
% test_ood_plan_face - T432_ACTIVATION_AMENDMENT_01 OOD face of the plan
% layer (T-018 Phase 4-D).  The OOD-directed mode (fleet_v3 member_exec
% 'OODMode', true) lowers the plan/nav HT floor from the IID support 1.5
% to the activation hard floor 1.3 and clamps the UKC factor at its
% HT=1.5 value over [1.3, 1.5) - the FD3 formula is never extrapolated
% below its validated support.  The default (IID) face is unchanged.
%
% Assertions:
%   1. plan_compose default face at ht=1.4 -> GATE:...:HT_BELOW_SUPPORT
%      (IID discipline unchanged);
%   2. plan_compose OOD face at ht=1.4 -> past the HT guard (any
%      downstream error is not the HT guard; the synthetic realization is
%      intentionally minimal);
%   3. plan_compose OOD face at ht=1.25 -> HT_BELOW_SUPPORT (the 1.3
%      activation floor is enforced on the OOD face too);
%   4. nav_constraints zones default face at ht=1.4 -> HT_BELOW_SUPPORT;
%   5. nav_constraints zones OOD face at ht=1.4 with a SHOAL work
%      segment -> UKC zone emitted with the clamped factor
%      (v_limit = 0.5 x v_host);
%   6. nav_constraints zones OOD face at ht=1.25 -> HT_BELOW_SUPPORT.
%
% Error ids: GATE:FLEETV3:TEST:PLANFACE.
%
% Discipline: ASCII-only source; no absolute paths; synthetic
% realization is construct-only (never written anywhere).

    ok = true;
    sg = struct('index', 1, 'role', 'work', 'reach', 'SHOAL', ...
        'direction', 'outbound', 'along_sign', 1, 'window_s', 100, ...
        't_start_nominal_s', 0, 'planned_speed_mps', 3.0, ...
        'u_signed_min', 0, 'u_signed_mean', 0, 'u_adverse_abs_sup', 0, ...
        'on_grid', true);
    mk = @(ht) struct('kind', 'realize', 'formal_seed', 'S', ...
        'base_draw_index', 1, 'stratum_id', 'STRAT_WORK_MISSION__DRY', ...
        'template_id', 'WORK_MISSION', 'regime_id', 'DRY', ...
        'operator_profile', 'CALM', 'segments', sg, ...
        'traffic', struct([]), ...
        'water', struct('ht_effective', ht, 'h_chart_m', 3.86, ...
        'delta_wl_m', -0.8, 'draft_m', 2.188), ...
        'ou', struct('dt_s', 1, 't_end_s', 100, 'prehistory_s', 0));

    % 1. default face at 1.4 -> HT_BELOW_SUPPORT
    [e1, id1] = local_try(@() mission_v3.plan_compose('compose', ...
        mk(1.4)));
    assert(strcmp(id1, 'GATE:MISSION_V3:PLAN:HT_BELOW_SUPPORT'), ...
        'GATE:FLEETV3:TEST:PLANFACE', ...
        'default face at ht=1.4 must keep the IID floor (got %s)', id1);

    % 2. OOD face at 1.4 -> past the HT guard
    [e2, id2] = local_try(@() mission_v3.plan_compose('compose', ...
        mk(1.4), 'OODMode', true));
    assert(~strcmp(id2, 'GATE:MISSION_V3:PLAN:HT_BELOW_SUPPORT'), ...
        'GATE:FLEETV3:TEST:PLANFACE', ...
        'OOD face at ht=1.4 must pass the HT guard (got %s)', id2);

    % 3. OOD face at 1.25 -> below the activation hard floor
    [~, id3] = local_try(@() mission_v3.plan_compose('compose', ...
        mk(1.25), 'OODMode', true));
    assert(strcmp(id3, 'GATE:MISSION_V3:PLAN:HT_BELOW_SUPPORT'), ...
        'GATE:FLEETV3:TEST:PLANFACE', ...
        'OOD face at ht=1.25 must enforce the 1.3 floor (got %s)', id3);

    % 4. zones default face at 1.4 -> HT_BELOW_SUPPORT
    [~, id4] = local_try(@() mission_v3.nav_constraints('zones', ...
        mk(1.4)));
    assert(strcmp(id4, 'GATE:MISSION_V3:NAV:HT_BELOW_SUPPORT'), ...
        'GATE:FLEETV3:TEST:PLANFACE', ...
        'zones default face at ht=1.4 must keep the IID floor (got %s)', ...
        id4);

    % 5. zones OOD face at 1.4 -> UKC zone with the clamped factor
    z = mission_v3.nav_constraints('zones', mk(1.4), 'OODMode', true);
    assert(numel(z.speed_limit_zones) == 1, ...
        'GATE:FLEETV3:TEST:PLANFACE', ...
        'zones OOD face at ht=1.4 must emit exactly one UKC zone');
    assert(abs(double(z.speed_limit_zones(1).v_limit_mps) ...
        - 0.5 * 3.0) < 1e-9, 'GATE:FLEETV3:TEST:PLANFACE', ...
        'UKC factor must clamp at the HT=1.5 value (0.5 x v_host)');

    % 6. zones OOD face at 1.25 -> below the activation hard floor
    [~, id6] = local_try(@() mission_v3.nav_constraints('zones', ...
        mk(1.25), 'OODMode', true));
    assert(strcmp(id6, 'GATE:MISSION_V3:NAV:HT_BELOW_SUPPORT'), ...
        'GATE:FLEETV3:TEST:PLANFACE', ...
        'zones OOD face at ht=1.25 must enforce the 1.3 floor');

    fprintf('test_ood_plan_face: PASS (OOD floor 1.3 + default face unchanged + UKC clamp)\n');
end

function [err, id] = local_try(fn)
    err = '';
    id = '';
    try
        fn();
    catch ME
        err = ME.message;
        id = ME.identifier;
    end
end
