%% test_ood_judge.m - fleet_v3 OOD acceptance-band judgment suite
% (T-018 Phase 4-D; D5 pipeline segments 3~5 on synthetic realizations).
% Covers A1/A2/B1 numeric band boundaries (endpoints), guard-band
% rejection (both directions), STRESS_SET removal (hard bounds), the
% no-target reject path, C-condition token membership, and token
% priority over a simultaneous numerical hit.  Model E physics
% parameters are provisioned into the base workspace because every
% ACCEPT path runs the 700 kW feasibility guard.  Failures raise
% GATE:FLEETV3:TEST:JUDGE.
% Discipline: ASCII-only; no absolute paths.

ra_root = fileparts(fileparts(fileparts(fileparts(mfilename('fullpath')))));
if isempty(ra_root) || ~exist(fullfile(ra_root, 'config'), 'dir')
    ra_root = pwd;
end
ra_act = fullfile(fileparts(fileparts(ra_root)), 'docs', 'phase4', ...
    'd_dataset_v3', 't432_activation_record.json');
ra_plan = fleet_v3.plan_load(ra_act, 'stage_a');

% provision the Model E physics parameters the propulsion guard consumes
% (config script only - no model load in this suite)
evalin('base', sprintf("run('%s')", ...
    fullfile(ra_root, 'config', 'ModelE_Physics_Parameters.m')));

% ---- A1 boundaries (deep-water realization, no token interference) ----
ra_j = fleet_v3.ood_judge(ra_plan, 'A1', local_rl(2.0, 3.2, ...
    {'departure', 'patrol', 'return'}));
assert(strcmp(ra_j.disposition, 'REJECT_GUARD_BAND'), ...
    'GATE:FLEETV3:TEST:JUDGE', 'sup=2.0 must sit in the adverse guard band (1.8, 2.0]');
assert(strcmp(ra_j.evidence.flow_axis, 'following'), ...
    'GATE:FLEETV3:TEST:JUDGE', 'a return segment must select the following guard');

ra_j = fleet_v3.ood_judge(ra_plan, 'A1', local_rl(2.0001, 3.2, ...
    {'departure', 'patrol', 'return'}));
assert(strcmp(ra_j.disposition, 'ACCEPT') && strcmp(ra_j.ood_axis, 'A'), ...
    'GATE:FLEETV3:TEST:JUDGE', 'sup just above 2.0 must enter A1');
assert(strcmp(ra_j.ood_condition_id, 'A1'), 'GATE:FLEETV3:TEST:JUDGE', ...
    'A1 condition id not propagated');

ra_j = fleet_v3.ood_judge(ra_plan, 'A1', local_rl(2.4, 3.2, ...
    {'departure', 'patrol', 'return'}));
assert(strcmp(ra_j.disposition, 'ACCEPT'), 'GATE:FLEETV3:TEST:JUDGE', ...
    'sup=2.4 must be inside A1 (closed upper endpoint)');

% adverse-only realization (no return segment): the guard is (1.8, 2.0],
% so sup=1.7 sits below it and outside A1 -> plain no-target reject
ra_j = fleet_v3.ood_judge(ra_plan, 'A1', local_rl(1.7, 3.2, ...
    {'departure', 'patrol'}));
assert(strcmp(ra_j.disposition, 'REJECT_NO_TARGET'), ...
    'GATE:FLEETV3:TEST:JUDGE', 'sup below the guard must reject as no-target');
% with a return segment the following guard (1.5, 2.0] binds instead
ra_j = fleet_v3.ood_judge(ra_plan, 'A1', local_rl(1.7, 3.2, ...
    {'departure', 'patrol', 'return'}));
assert(strcmp(ra_j.disposition, 'REJECT_GUARD_BAND'), ...
    'GATE:FLEETV3:TEST:JUDGE', ...
    'sup=1.7 inside the following guard band must reject as guard band');

% ---- A2 boundaries ----
ra_j = fleet_v3.ood_judge(ra_plan, 'A2', local_rl(2.4001, 3.2, ...
    {'departure', 'cruise'}));
assert(strcmp(ra_j.disposition, 'ACCEPT') && strcmp(ra_j.ood_axis, 'A'), ...
    'GATE:FLEETV3:TEST:JUDGE', 'A2 lower endpoint must be exclusive');
% sup=2.8 sits exactly on the hard bound, but the conservative 700 kW
% propulsion guard already removes such candidates (demand ~753 kW at
% 11 kn adverse, deep water): the D5 removal face, not the band, binds
ra_j = fleet_v3.ood_judge(ra_plan, 'A2', local_rl(2.8, 3.2, ...
    {'departure', 'cruise'}));
assert(strcmp(ra_j.disposition, 'STRESS_SET') ...
    && ~isempty(ra_j.evidence.propulsion), ...
    'GATE:FLEETV3:TEST:JUDGE', ...
    'A2 upper end must be removed by the 700 kW propulsion guard');
ra_j = fleet_v3.ood_judge(ra_plan, 'A2', local_rl(2.42, 3.2, ...
    {'departure', 'cruise'}));
assert(strcmp(ra_j.disposition, 'ACCEPT'), 'GATE:FLEETV3:TEST:JUDGE', ...
    'A2 inside the propulsion-feasible sub-band must accept');
ra_j = fleet_v3.ood_judge(ra_plan, 'A2', local_rl(2.81, 3.2, ...
    {'departure', 'cruise'}));
assert(strcmp(ra_j.disposition, 'STRESS_SET'), ...
    'GATE:FLEETV3:TEST:JUDGE', 'sup above 2.8 must be STRESS_SET');

% ---- B1 boundaries (adverse-only realization) ----
ra_j = fleet_v3.ood_judge(ra_plan, 'B1', local_rl(0.4, 1.3, ...
    {'departure', 'harbor'}));
assert(strcmp(ra_j.disposition, 'ACCEPT') && strcmp(ra_j.ood_axis, 'B'), ...
    'GATE:FLEETV3:TEST:JUDGE', 'ht=1.3 must enter B1 (closed lower endpoint)');
ra_j = fleet_v3.ood_judge(ra_plan, 'B1', local_rl(0.4, 1.5, ...
    {'departure', 'harbor'}));
assert(strcmp(ra_j.disposition, 'REJECT_NO_TARGET'), ...
    'GATE:FLEETV3:TEST:JUDGE', 'ht=1.5 must leave B1 (open upper endpoint)');
ra_j = fleet_v3.ood_judge(ra_plan, 'B1', local_rl(0.4, 1.29, ...
    {'departure', 'harbor'}));
assert(strcmp(ra_j.disposition, 'STRESS_SET'), ...
    'GATE:FLEETV3:TEST:JUDGE', 'ht below 1.3 must be STRESS_SET');
ra_j = fleet_v3.ood_judge(ra_plan, 'B1', local_rl(0.4, 1.1, ...
    {'departure', 'harbor'}));
assert(strcmp(ra_j.disposition, 'STRESS_SET'), ...
    'GATE:FLEETV3:TEST:JUDGE', 'ht below the 1.2 hard floor must be STRESS_SET');

% ---- C membership: canonical token REQUIRE face ----
ra_j = fleet_v3.ood_judge(ra_plan, 'C2', local_rl(0.4, 1.7, ...
    {'harbor', 'cruise', 'return'}));
assert(strcmp(ra_j.disposition, 'ACCEPT') && strcmp(ra_j.ood_axis, 'C') ...
    && strcmp(ra_j.ood_token_id, 'C2_HARBOR_X_LOW_ID_HT'), ...
    'GATE:FLEETV3:TEST:JUDGE', 'C2 token membership failed');
ra_j = fleet_v3.ood_judge(ra_plan, 'C2', local_rl(0.4, 1.45, ...
    {'harbor', 'return'}));
assert(strcmp(ra_j.disposition, 'REJECT_NO_TARGET'), ...
    'GATE:FLEETV3:TEST:JUDGE', 'C2 with ht outside the band must reject');
ra_j = fleet_v3.ood_judge(ra_plan, 'C3', local_rl(0.4, 1.7, ...
    {'standby', 'rush', 'return'}));
assert(strcmp(ra_j.disposition, 'ACCEPT') ...
    && strcmp(ra_j.ood_token_id, 'C3_EMERGENCY_SPRINT_X_LOW_ID_HT'), ...
    'GATE:FLEETV3:TEST:JUDGE', 'C3 token membership failed');

% ---- token priority: A1 numerical hit + simultaneous C1 token -> C ----
% (bridge segment adverse sup inside [1.4, 1.8] while the voyage sup is
%  inside A1 - the token axis wins per the frozen priority rule)
ra_j = fleet_v3.ood_judge(ra_plan, 'A1', local_rl(2.2, 3.2, ...
    {'departure', 'bridge', 'return'}, [2.2, 1.6, 2.2]));
assert(strcmp(ra_j.disposition, 'ACCEPT') && strcmp(ra_j.ood_axis, 'C'), ...
    'GATE:FLEETV3:TEST:JUDGE', 'token must win the axis over a numerical hit');
assert(strncmp(ra_j.ood_token_id, 'C1_BRIDGE', 9), ...
    'GATE:FLEETV3:TEST:JUDGE', 'token priority recorded the wrong token');
assert(strcmp(ra_j.ood_condition_id, 'C1'), ...
    'GATE:FLEETV3:TEST:JUDGE', 'token priority must follow the token condition');

% ---- following-direction guard band: return + sup in (1.5, 2.0] ----
ra_j = fleet_v3.ood_judge(ra_plan, 'C2', local_rl(1.7, 1.7, ...
    {'harbor', 'return'}));
assert(strcmp(ra_j.disposition, 'REJECT_GUARD_BAND'), ...
    'GATE:FLEETV3:TEST:JUDGE', ...
    'following guard band (1.5, 2.0] must reject a C candidate');

% ---- 700 kW guard: low H/T with a strong adverse flow is a removal ----
ra_j = fleet_v3.ood_judge(ra_plan, 'B1', local_rl(2.3, 1.35, ...
    {'departure', 'harbor'}));
assert(strcmp(ra_j.disposition, 'STRESS_SET'), ...
    'GATE:FLEETV3:TEST:JUDGE', ...
    'high-flow low-ht candidate must fail the propulsion guard');
assert(~isempty(ra_j.evidence.propulsion) ...
    && ~ra_j.evidence.propulsion.feasible, ...
    'GATE:FLEETV3:TEST:JUDGE', 'propulsion evidence not attached');

fprintf('test_ood_judge: PASS (A1/A2/B1 boundaries + guard bands + stress + tokens + priority + 700kW)\n');

function rl = local_rl(sup, ht, roles, adv_sup)
% Synthetic env_realize-style realization: constant flow series at the
% requested sup, realized ht, and per-segment role/adverse summaries.
    n = 64;
    rl = struct();
    rl.kind = 'realize';
    rl.u_river_mps = sup * ones(1, n);
    w = struct('h_chart_m', ht * 2.188, 'delta_wl_m', 0.0, ...
        'h_effective_m', ht * 2.188, 'draft_m', 2.188, ...
        'ht_effective', ht);
    rl.water = w;
    nseg = numel(roles);
    seg = repmat(struct('index', 0, 'role', '', 'reach', '', ...
        'direction', '', 'along_sign', 0, 'stretch', 1.0, ...
        'planned_speed_mps', [], 'window_s', 100.0, ...
        't_start_nominal_s', 0.0, 'idx_start', 1, 'idx_end', n, ...
        't_start_s', 0.0, 't_end_s', 100.0, 'u_abs_sup', sup, ...
        'u_signed_min', -sup, 'u_signed_max', sup, 'u_signed_mean', 0.0, ...
        'u_adverse_abs_sup', sup, 'u_following_abs_sup', sup, ...
        'on_grid', true), 1, nseg);
    for i = 1:nseg
        seg(i).index = i;
        seg(i).role = roles{i};
        if nargin >= 4
            seg(i).u_adverse_abs_sup = adv_sup(i);
        end
    end
    rl.segments = seg;
end
