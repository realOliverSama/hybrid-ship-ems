%% test_plan_load.m - fleet_v3 plan loader suite (T-018 Phase 4-D).
% Run from the Model E workspace root (run_all.m executes this script):
% covers structural parsing of the FROZEN activation record, band
% decoding, override key paths, segment parameterization and provenance
% hash stability.  Failures raise GATE:FLEETV3:TEST:PLAN_LOAD.
% Discipline: ASCII-only; no absolute paths (ROOT via mfilename).

ra_root = fileparts(fileparts(fileparts(fileparts(mfilename('fullpath')))));
if isempty(ra_root) || ~exist(fullfile(ra_root, 'config'), 'dir')
    ra_root = pwd;
end
ra_act = fullfile(fileparts(fileparts(ra_root)), 'docs', 'phase4', ...
    'd_dataset_v3', 't432_activation_record.json');

ra_plan = fleet_v3.plan_load(ra_act, 'stage_a');

% ---- qualification criteria injected from the record ----
assert(ra_plan.qual.min_duration_s == 1200, 'GATE:FLEETV3:TEST:PLAN_LOAD', ...
    'min_duration_s != 1200');
assert(ra_plan.qual.min_canonical_windows == 60, ...
    'GATE:FLEETV3:TEST:PLAN_LOAD', 'min_canonical_windows != 60');
assert(ra_plan.qual.unexpected_invalid_max == 0, ...
    'GATE:FLEETV3:TEST:PLAN_LOAD', 'unexpected_invalid_max != 0');

% ---- IID segment + gates ----
assert(strcmp(ra_plan.iid.seed, 'MISSION_V3_T432_STAGEA_SEED_2026_09_07'), ...
    'GATE:FLEETV3:TEST:PLAN_LOAD', 'stage_a seed mismatch');
assert(ra_plan.iid.draw_base == 900 && ra_plan.iid.draws == 2, ...
    'GATE:FLEETV3:TEST:PLAN_LOAD', 'stage_a IID segment != k=900..901');
assert(numel(ra_plan.iid.strata) == 9, 'GATE:FLEETV3:TEST:PLAN_LOAD', ...
    'n_strata != 9');
assert(ra_plan.iid.members_per_family == 4, ...
    'GATE:FLEETV3:TEST:PLAN_LOAD', 'members_per_family != 4');
assert(ra_plan.iid.retry_max == 2, 'GATE:FLEETV3:TEST:PLAN_LOAD', ...
    'retry_max != 2');
assert(ra_plan.iid.thr_stratum == 0.5 && ra_plan.iid.thr_overall == 0.5, ...
    'GATE:FLEETV3:TEST:PLAN_LOAD', 'rejection gates != 0.5');
% formal Stage B parameterization (Phase 2)
assert(ra_plan.iid.draw_stride == 1000 && ra_plan.iid.k_formal == 16, ...
    'GATE:FLEETV3:TEST:PLAN_LOAD', 'formal IID draw rule mismatch');
assert(strcmp(ra_plan.iid.seed_formal, ...
    'MISSION_V3_T432_FORMAL_SEED_2026_09_07'), ...
    'GATE:FLEETV3:TEST:PLAN_LOAD', 'formal seed mismatch');

% ---- OOD segment + bands (parsed, not hand-copied) ----
assert(strcmp(ra_plan.ood.def_version, 'DGN-11-v1'), ...
    'GATE:FLEETV3:TEST:PLAN_LOAD', 'def_version mismatch');
assert(isequal(ra_plan.ood.conditions, ...
    {'A1', 'B1', 'C1', 'C2', 'C3'}), ...
    'GATE:FLEETV3:TEST:PLAN_LOAD', ...
    'condition order mismatch (amendment 01: A2 retired, 5 conditions)');
assert(~isempty(ra_plan.provenance.amendment_sha256) ...
    && ~strcmp(ra_plan.provenance.amendment_sha256, ...
    ra_plan.provenance.activation_sha256), ...
    'GATE:FLEETV3:TEST:PLAN_LOAD', ...
    'amendment chain not consumed (amendment_sha256 missing/collapsed)');
assert(ra_plan.ood.band_A1.min == 2.0 && ~ra_plan.ood.band_A1.min_incl ...
    && ra_plan.ood.band_A1.max == 2.4 && ra_plan.ood.band_A1.max_incl, ...
    'GATE:FLEETV3:TEST:PLAN_LOAD', 'A1 band != (2.0, 2.4]');
assert(ra_plan.ood.stress_investigation_band.min == 2.4 ...
    && ~ra_plan.ood.stress_investigation_band.min_incl ...
    && ra_plan.ood.stress_investigation_band.max == 2.8 ...
    && ra_plan.ood.stress_investigation_band.max_incl, ...
    'GATE:FLEETV3:TEST:PLAN_LOAD', ...
    'A2 investigation band != (2.4, 2.8] (amendment 01)');
assert(ra_plan.ood.band_B1.min == 1.3 && ra_plan.ood.band_B1.min_incl ...
    && ra_plan.ood.band_B1.max == 1.5 && ~ra_plan.ood.band_B1.max_incl, ...
    'GATE:FLEETV3:TEST:PLAN_LOAD', 'B1 band != [1.3, 1.5)');
assert(ra_plan.ood.guard_adverse.min == 1.8 ...
    && ~ra_plan.ood.guard_adverse.min_incl ...
    && ra_plan.ood.guard_adverse.max == 2.0 ...
    && ra_plan.ood.guard_adverse.max_incl, ...
    'GATE:FLEETV3:TEST:PLAN_LOAD', 'adverse guard != (1.8, 2.0]');
assert(ra_plan.ood.guard_following.min == 1.5 ...
    && ~ra_plan.ood.guard_following.min_incl ...
    && ra_plan.ood.guard_following.max == 2.0 ...
    && ra_plan.ood.guard_following.max_incl, ...
    'GATE:FLEETV3:TEST:PLAN_LOAD', 'following guard != (1.5, 2.0]');
assert(ra_plan.ood.stress_band.min == 1.2 && ra_plan.ood.stress_band.max == 1.3 ...
    && ra_plan.ood.stress_band.min_incl && ~ra_plan.ood.stress_band.max_incl, ...
    'GATE:FLEETV3:TEST:PLAN_LOAD', 'stress band != [1.2, 1.3)');
assert(ra_plan.ood.ht_domain_floor == 1.2 && ra_plan.ood.sup_domain_max == 2.8, ...
    'GATE:FLEETV3:TEST:PLAN_LOAD', 'hard bounds mismatch');
assert(ra_plan.ood.train_support_min_ht == 1.5, ...
    'GATE:FLEETV3:TEST:PLAN_LOAD', 'train_support_min_ht != 1.5');
assert(ra_plan.ood.draw_base == 900, 'GATE:FLEETV3:TEST:PLAN_LOAD', ...
    'stage_a OOD segment != k=900');
assert(ra_plan.ood.seed_base == 10000 && ra_plan.ood.seed_stride == 1000 ...
    && ra_plan.ood.families_formal == 10, ...
    'GATE:FLEETV3:TEST:PLAN_LOAD', 'formal OOD seed rule mismatch');

% ---- hosts + proposal samplers (parsed from the frozen record) ----
h = ra_plan.ood.hosts;
assert(strcmp(h.A1.regime, 'FLOOD') && strcmp(h.A1.template, 'ROUTINE_PATROL'), ...
    'GATE:FLEETV3:TEST:PLAN_LOAD', 'A1 host mismatch');
assert(strcmp(h.B1.regime, 'DRY'), 'GATE:FLEETV3:TEST:PLAN_LOAD', ...
    'B1 host mismatch');
assert(strcmp(h.C1.regime, 'FLOOD') && strcmp(h.C1.token_id, ...
    'C1_BRIDGE_X_HIGH_ID_ADVERSE_CURRENT'), ...
    'GATE:FLEETV3:TEST:PLAN_LOAD', 'C1 host/token mismatch');
assert(strcmp(h.C2.regime, 'DRY') && strcmp(h.C3.template, ...
    'EMERGENCY_RESPONSE'), 'GATE:FLEETV3:TEST:PLAN_LOAD', ...
    'C2/C3 host mismatch');
p1 = ra_plan.ood.proposal.A1;
assert(abs(p1.mu - 2.2) < 1e-12 && abs(p1.sigma - 0.15) < 1e-12 ...
    && abs(p1.lower - 2.05) < 1e-12 && abs(p1.upper_uninjected - 2.4) < 1e-12, ...
    'GATE:FLEETV3:TEST:PLAN_LOAD', 'A1 sampler mismatch');
ov = p1.override;
assert(ov.regimes.FLOOD.u_river_mag.mu == 2.2 ...
    && ov.regimes.FLOOD.u_river_mag.sigma == 0.15 ...
    && ov.regimes.FLOOD.u_river_mag.lower == 2.05, ...
    'GATE:FLEETV3:TEST:PLAN_LOAD', 'A1 override key path mismatch');
pb = ra_plan.ood.proposal.B1;
assert(pb.override.chart_depth_voyage_base.mu == 3.86 ...
    && pb.override.chart_depth_voyage_base.sigma == 0.15 ...
    && pb.override.chart_depth_voyage_base.lower == 3.64, ...
    'GATE:FLEETV3:TEST:PLAN_LOAD', 'B1 override key path mismatch');
pc = ra_plan.ood.proposal.C1;
assert(isfield(pc, 'override') && isempty(fieldnames(pc.override)), ...
    'GATE:FLEETV3:TEST:PLAN_LOAD', 'C1 must carry no override');

% ---- smoke segment ----
sm = fleet_v3.plan_load(ra_act, 'smoke');
assert(sm.smoke.draw_base == 950 && sm.smoke.iid_strata == 2 ...
    && sm.smoke.iid_draws == 1 && sm.smoke.ood_families == 1, ...
    'GATE:FLEETV3:TEST:PLAN_LOAD', 'smoke segment != k=950 x 2 strata');
assert(strcmp(sm.iid.seed, ra_plan.iid.seed), ...
    'GATE:FLEETV3:TEST:PLAN_LOAD', 'smoke seed != stage_a seed');

% ---- provenance hash stability (two loads -> identical hashes) ----
ra_plan2 = fleet_v3.plan_load(ra_act, 'stage_a');
assert(strcmp(ra_plan.provenance.activation_sha256, ...
    ra_plan2.provenance.activation_sha256), ...
    'GATE:FLEETV3:TEST:PLAN_LOAD', 'activation hash unstable');
assert(strcmp(ra_plan.provenance.ood_override_sha256, ...
    ra_plan2.provenance.ood_override_sha256), ...
    'GATE:FLEETV3:TEST:PLAN_LOAD', 'override config hash unstable');
assert(strcmp(ra_plan.provenance.heldout_registry_sha, ...
    '83d84d0c890079e55fe2159f0e61d08f888053dc5127a48d8419680dc8df1b25'), ...
    'GATE:FLEETV3:TEST:PLAN_LOAD', 'registry self_hash binding broken');
% ^ frozen-binding contract test: the literal is the self_hash of the
%   FROZEN config/mission_v3/heldout_token_registry.json; any change to
%   that registry must fail loudly here (generation-side code itself
%   consumes the hash from the file, never this literal).
ra_sm2 = fleet_v3.plan_load(ra_act, 'smoke');
assert(strcmp(sm.provenance.ood_override_sha256, ...
    ra_sm2.provenance.ood_override_sha256), ...
    'GATE:FLEETV3:TEST:PLAN_LOAD', 'smoke override hash unstable');
assert(~strcmp(ra_plan.provenance.ood_override_sha256, ...
    ra_plan.provenance.activation_sha256), ...
    'GATE:FLEETV3:TEST:PLAN_LOAD', 'provenance hashes collapsed');

% ---- negative: bad mode fails closed ----
ra_threw = false;
try
    fleet_v3.plan_load(ra_act, 'stage_b');
catch ME
    ra_threw = strncmp(char(ME.identifier), 'GATE:FLEETV3:PLAN', 17);
end
assert(ra_threw, 'GATE:FLEETV3:TEST:PLAN_LOAD', ...
    'bad mode did not fail closed');

fprintf('test_plan_load: PASS (activation parse + bands + samplers + segments + hash stability)\n');
