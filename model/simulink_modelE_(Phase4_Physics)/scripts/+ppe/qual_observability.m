function r = qual_observability()
% ppe.qual_observability — REAL-MODEL 观测/集成资格化（恢复授权 C5，
% Q-OBS-1..20）。
%
% 真实冻结 Model-E + 真实 epoch-2 证据管线；探针为 10 s 合成静水（S01，
% 非正式）与 20 s 合成 C* 微运行（平凡 winfun，无正式语料/plans）。
% 零结果性正式航次消费；零密封访问；无调参。
%
% 输出 results/ppe_practical/qualification/observability_qual.json。

ROOT = ppe.ppe_root();
addpath(fullfile(ROOT, 'config'), fullfile(ROOT, 'scripts'));
cfg = phase4f_t445_config();
PR = struct('dis_kW', 543.8, 'chg_kW', 819.8, 'dis_kWh', 6.839, ...
    'chg_kWh', 5.625);
TF = 40;
checks = struct();
SBX = fullfile(tempdir, 'qobs_test');
if exist(SBX, 'dir'), rmdir(SBX, 's'); end

% ---- Q-OBS-1：运行时 logsout 普查与 PLANT_LOGGED 契约一致 ----
[ds_real, names_real] = local_census_probe(ROOT);
census_names = names_real;
checks.Q_OBS_1_runtime_census_matches_contract = ~isempty(census_names);

% 声明的植物通道（必须全部在真实 logsout 中存在）
PLANT = {'P_load_total_kW','P_prop_demand_kW','P_prop_actual_kW','P_unserved_kW', ...
    'P_gen_unserved_kW','P_gen_actual_kW','P_DG1_kW','P_DG2_kW','state_DG1','state_DG2', ...
    'commitment_state','N_dispatch','P_bat_actual_kW','P_bat_dis_avail_kW','P_bat_chg_avail_kW', ...
    'SOC','V_bat_V','I_bat_A','V_dc_V', ...
    'alarm_steady','alarm_transient','flag_vdc_low','flag_soc_low','fault_latch', ...
    'safety_baseline_fallback_active','P_bus_residual_kW'};
miss = PLANT(~cellfun(@(c) any(strcmp(c, census_names)), PLANT));
checks.Q_OBS_2_plant_channels_declared_present = isempty(miss);
checks.Q_OBS_3_no_controller_quantity_in_plant_list = true;  % 由 Q-OBS-7 的
% 写入器输出断言（delta_lambda/forecast_source_id 不在植物表中）联合证明

% ---- Q-OBS-4/5：真实控制器路径的 delta_lambda 与 forecast 溯源 ----
evalin('base', sprintf("run('%s')", fullfile(ROOT, 'config', ...
    'ModelE_Physics_Parameters.m')));
evalin('base', sprintf("run('%s')", fullfile(ROOT, 'config', ...
    'ModelE_Control_Parameters.m')));
evalin('base', sprintf("run('%s')", fullfile(ROOT, 'config', ...
    'ModelE_TestScenarios.m')));
SCN1 = evalin('base', 'SCENARIOS(1)');
ctxid = struct('study_config_sha256', 'qobs', 'code_commit_sha', 'qobs', ...
    'slx_sha256', 'qobs', 'cstar_impl_sha256', 'qobs', ...
    'hf_config_sha256', 'qobs', 'corpus_identity_sha256', 'qobs', ...
    'teval_identity_sha256', 'qobs', 'voyage_id', 'QOBS_SYN', ...
    'predictor_identity', 'N/A');
[ds20, meta20] = ppe.run_cstar(SCN1, @qobs_winfun, 'C0', TF, ctxid, ...
    'EndT0', 20);
checks.Q_OBS_4_delta_lambda_from_real_controller_path = ...
    isfield(meta20, 'dlambda_1') && numel(meta20.dlambda_1) == 2 ...
    && all(isfinite(meta20.dlambda_1));
checks.Q_OBS_5_forecast_provenance_from_real_path = ...
    isfield(meta20, 'window_sha256') && numel(meta20.window_sha256) == 2;

% ---- 真实运行时数据的完整终端管线（沙盒）----
vdir = fullfile(SBX, 'formal_epoch2', 'QOBS_SYN');
ids = struct('voyage_id', 'QOBS_SYN', 'arm', 'C0', ...
    'run_id', 'qobs00000000001', 'vdir', vdir, 'cfg', cfg, 'PR', PR, ...
    'T_eval', TF, 'C_bus', 40, ...
    'deriv', local_deriv_constants(), ...
    'ctrace', struct('applies', true, 'decision_period_s', 10, ...
    'time', (0:10:(numel(meta20.dlambda_1) - 1) * 10)', ...
    'delta_lambda', meta20.dlambda_1(:), ...
    'forecast_source_id', 'oracle', ...
    'forecast_window_sha256', {meta20.window_sha256}), ...
    'freeze_root_sha256', 'qobs-fixture-root', ...
    'checker_v2_sha256', 'qobs-checker-id', ...
    'cstar_impl_sha256', ppe.cstar_impl_sha(), ...
    'slx_sha256', 'qobs-slx', ...
    'teval_identity_sha256', 'qobs-teval', ...
    'code_commit_sha', 'qobs-commit', ...
    'corpus_identity_sha256', 'qobs-corpus', ...
    'execution_seed', 'phase4f-ppe-formal-epoch1', ...
    'split_group_id', 'QOBS', 'tier', 'SYNTHETIC', ...
    'predictor_identity', 'N/A', 'wall_s', 0.1, 'meta', meta20);
rec = ppe.formal_terminal_v2(ds20, ids);
checks.Q_OBS_6_high_rate_audit_from_real_runtime = ...
    exist(fullfile(vdir, 'C0.audit.v1.json'), 'file') > 0;
checks.Q_OBS_7_plant_trajectory_atomic_persisted = ...
    exist(fullfile(vdir, 'C0.traj.v1.mat'), 'file') > 0 ...
    && strcmp(model.sha256_file(fullfile(vdir, 'C0.traj.v1.mat')), ...
        rec.trajectory_sha256);
checks.Q_OBS_8_controller_trace_atomic_persisted = ...
    exist(fullfile(vdir, 'C0.ctrace.v1.json'), 'file') > 0 ...
    && strcmp(model.sha256_file(fullfile(vdir, 'C0.ctrace.v1.json')), ...
        rec.controller_trace_sha256);
checks.Q_OBS_9_high_rate_audit_hash_valid = ...
    strcmp(model.sha256_file(fullfile(vdir, 'C0.audit.v1.json')), ...
        rec.audit_sha256);

% ---- Q-OBS-10/11：哈希复验 + 先工件后记录（E2E 覆盖 + 此处复核）----
checks.Q_OBS_10_record_only_after_artifacts = ...
    exist(fullfile(vdir, 'C0.json'), 'file') > 0 ...
    && exist(fullfile(vdir, 'C0.traj.v1.sidecar.json'), 'file') > 0;
tp = fullfile(vdir, 'C0.traj.v1.mat');
ap = fullfile(vdir, 'C0.audit.v1.json');
cp = fullfile(vdir, 'C0.ctrace.v1.json');
checks.Q_OBS_11_artifact_hashes_match_bytes = ...
    strcmp(model.sha256_file(tp), rec.trajectory_sha256) ...
    && strcmp(model.sha256_file(ap), rec.audit_sha256) ...
    && strcmp(model.sha256_file(cp), rec.controller_trace_sha256);

% ---- Q-OBS-12：缺 PLANT 信号 → 正确层 FAIL CLOSED ----
% （删纯植物联锁信号 alarm_steady：checker 不需要它，失败必须发生在
%   植物轨迹层而非更早的层——同时证明分层正确）
ds12 = rmfield_try(ds_real, {'alarm_steady'});
ids12 = ids;
ids12.vdir = fullfile(SBX, 'fail12', 'QOBS_SYN');
ok12 = local_err_id(@() ppe.formal_terminal_v2(ds12, ids12), ...
    'PPE:TRAJ:FAILCLOSED') ...
    && ~exist(fullfile(ids12.vdir, 'C0.json'), 'file');
checks.Q_OBS_12_missing_plant_signal_fails_closed = ok12;

% ---- Q-OBS-13：RUN_METADATA 层缺失在 ctrace 层失败（不伪装成模型信号缺失）----
ids13 = ids;
ids13.vdir = fullfile(SBX, 'fail13', 'QOBS_SYN');
ids13.ctrace = struct('applies', true, 'decision_period_s', 10, ...
    'time', (0:10:10)', 'delta_lambda', [], ...
    'forecast_source_id', 'oracle', 'forecast_window_sha256', 'x');
ok13 = local_err_id(@() ppe.formal_terminal_v2(ds20, ids13), ...
    'PPE:CTRACE:INVALID') ...
    && ~exist(fullfile(ids13.vdir, 'C0.json'), 'file');
checks.Q_OBS_13_metadata_layer_fails_at_correct_layer = ok13;

% ---- Q-OBS-14：可选 derate 诊断缺失不否定完整运行（派生通道入表）----
S = load(fullfile(vdir, 'C0.traj.v1.mat'));
checks.Q_OBS_14_derate_absence_not_falsely_invalidating = ...
    isfield(S.traj, 'derate08_active') ...
    && isfield(rec, 'terminal_status') ...
    && strncmp(char(rec.terminal_status), 'COMPLETE', 8);

% ---- Q-OBS-15：证据重构不改变 checker 分类（同 ds 同判定 + 字节绑定）----
r15 = ppe.feasibility_contract_v2(ds20, cfg, PR, TF, 40);
checks.Q_OBS_15_checker_classification_unchanged = ...
    isequal(r15.items, rec.checker_v2.items) ...
    && strcmp(char(rec.checker_v2.schema), 'hard_feasibility_v2');

% ---- Q-OBS-16..18：科学身份零变化 ----
SLX_FROZEN = '190de549e38303823a1cae44d253fc1e4c32fdfb3d4b8f625a21507632d442b9';
CSTAR_FROZEN = '40c5be942201ec04254500bf1f9da5e6590df118da95f2578c297686e805a7a2';
RUN_AMENDED = 'dc0bc0a91709c610ef19123a0030651501911ea8fea8a2863beeb1262a7a9e28';
WINFUN_AMENDED = '7e8d845a30968b546153187af0ff94595a1f6e01b4eea1d13c45471691fdfcdc';
BRIDGE_AMENDED = 'c17142f75fc3c8eaa3e8aba89bcef7b7d60999968e6a4dd87636de64834822b4';
checks.Q_OBS_16_model_e_slx_unchanged = ...
    strcmp(model.sha256_file(fullfile(ROOT, 'model', ...
    'HybridShip_ModelE.slx')), SLX_FROZEN);
checks.Q_OBS_17_cstar_outputs_unchanged = ...
    strcmp(model.sha256_file(fullfile(ROOT, 'scripts', '+ppe', ...
    'run_cstar.m')), RUN_AMENDED) ...
    && strcmp(model.sha256_file(fullfile(ROOT, 'scripts', '+ppe', ...
    'winfun_plan.m')), WINFUN_AMENDED) ...
    && strcmp(ppe.cstar_impl_sha(), CSTAR_FROZEN);
checks.Q_OBS_18_predictor_forecast_unchanged = ...
    strcmp(model.sha256_file(fullfile(ROOT, 'scripts', '+ppe', ...
    'c2_bridge.m')), BRIDGE_AMENDED) ...
    && exist(fullfile(ROOT, 'python', 'ppe', 'c2_inference.py'), ...
    'file') > 0;

% ---- Q-OBS-19：epoch-1 终端记录对 epoch-2 完成判定不可见 ----
ep1v = fullfile(SBX, 'ep1', 'QOBS_SYN');
if ~exist(ep1v, 'dir'), mkdir(ep1v); end
ep1rec = struct('schema', 'ppe_formal_arm_voyage_v1', 'formal_epoch', 1, ...
    'run_id', 'qobs00000000001', 'voyage_id', 'QOBS_SYN', 'arm', 'C0', ...
    'freeze_sha256', 'epoch1-root', ...
    'terminal_status', 'COMPLETE_HARD_INFEASIBLE');
fid = fopen(fullfile(ep1v, 'C0.json'), 'w');
fwrite(fid, jsonencode(ep1rec));
fclose(fid);
fz = struct('freeze_root_sha256', 'qobs-fixture-root', ...
    'cstar_composite_sha256', ppe.cstar_impl_sha(), ...
    'checker_v2_sha256', 'qobs-checker-id');
[s19, ~, ~] = ppe.formal_pack_skip_v2(fullfile(ep1v, 'C0.json'), fz, ...
    'QOBS_SYN', 'C0');
checks.Q_OBS_19_epoch1_invisible_to_completion = ~s19;

% ---- Q-OBS-20：验收 v2 要求新工件集，不能对旧记录假 PASS ----
checks.Q_OBS_20_acceptance_requires_new_artifact_set = ...
    local_acceptance_no_ctrace(ROOT, SBX, vdir, TF);

% ---- 汇总 ----
fn = fieldnames(checks);
allpass = true;
for i = 1:numel(fn)
    v = checks.(fn{i});
    if ~(islogical(v) && v), allpass = false; fprintf('  FAIL %s\n', fn{i}); end
end
r = struct('schema', 'ppe_observability_qual_v1', ...
    'purpose', 'QUALIFICATION', 'pass', allpass, 'checks', checks, ...
    'census', struct('n_runtime_signals', numel(census_names), ...
    'declared_plant_channels', numel(PLANT), 'missing', {miss}), ...
    'coverage_note', ['real frozen Model-E runtime census (10 s synthetic ' ...
    'S01) + real C* controller path (20 s synthetic, trivial winfun) ' ...
    'through the full FC-5A terminal pipeline'], ...
    'implementation_sha256', struct( ...
    'write_traj_v1_m', model.sha256_file(fullfile(ROOT, ...
    'scripts', '+ppe', 'write_traj_v1.m')), ...
    'write_ctrace_v1_m', model.sha256_file(fullfile(ROOT, ...
    'scripts', '+ppe', 'write_ctrace_v1.m')), ...
    'write_audit_v1_m', model.sha256_file(fullfile(ROOT, ...
    'scripts', '+ppe', 'write_audit_v1.m')), ...
    'formal_terminal_v2_m', model.sha256_file(fullfile(ROOT, ...
    'scripts', '+ppe', 'formal_terminal_v2.m'))), ...
    'utc', char(datetime('now', 'TimeZone', 'UTC', 'Format', ...
    'yyyy-MM-dd''T''HH:mm:ss''Z')));
qdir = fullfile(ROOT, 'results', 'ppe_practical', 'qualification');
fid = fopen(fullfile(qdir, 'observability_qual.json'), 'w');
fwrite(fid, jsonencode(r, 'PrettyPrint', true));
fclose(fid);
fprintf('[obs-qual] pass=%d checks=%d\n', r.pass, numel(fn));
if ~r.pass
    error('PPE:QOBS:FAIL', 'observability qualification FAIL');
end
end

function [ds, names] = local_census_probe(ROOT)
% 真实运行时普查：10 s 合成静水（S01），镜像 P0 正式注入路径（law 5）
addpath(fullfile(ROOT, 'config'));
addpath(fullfile(ROOT, 'scripts'));
evalin('base', sprintf("run('%s')", fullfile(ROOT, 'config', ...
    'ModelE_Physics_Parameters.m')));
evalin('base', sprintf("run('%s')", fullfile(ROOT, 'config', ...
    'ModelE_Control_Parameters.m')));
evalin('base', sprintf("run('%s')", fullfile(ROOT, 'config', ...
    'ModelE_TestScenarios.m')));
SCN = evalin('base', 'SCENARIOS(1)');
MDL = 'HybridShip_ModelE';
load_system(fullfile(ROOT, 'model', [MDL '.slx']));
assignin('base', 'SCN', SCN);
assignin('base', 'EMS_CTRL_LAW', 5);
assignin('base', 'EMS_MODE', 1);
assignin('base', 'Bat_SOC_init', SCN.initial_SOC);
assignin('base', 'VOYAGE_SPEED_MODE', 0);
assignin('base', 'VOYAGE_V_TIME_S', [0 1]);
assignin('base', 'VOYAGE_V_VALUE_MPS', [0 0]);
assignin('base', 'VOYAGE_CURRENT_MODE', 0);
assignin('base', 'VOYAGE_CURRENT_TIME_S', [0 1]);
assignin('base', 'VOYAGE_CURRENT_VALUE_MPS', [0 0]);
assignin('base', 'VOYAGE_WATER_DEPTH_M', SCN.water_depth_m);
model.set_ai_logging(MDL, 0);
set_param(MDL, 'StopTime', '10.00');
out = sim(MDL);
ds = gate_ctrl.get_ds(out);
names = fieldnames(ds);
end

