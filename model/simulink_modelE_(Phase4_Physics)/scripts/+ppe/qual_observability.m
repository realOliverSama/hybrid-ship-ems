end

function d = local_deriv_constants()
d = struct('eta_rect', evalin('base', 'ASSUMED_eta_rect'), ...
    'ccs_v_hi', evalin('base', 'CCS_Vdc_Steady_Band(1)'), ...
    'ccs_v_lo', evalin('base', 'CCS_Vdc_Transient_Band(1)'));
end

function s = rmfield_try(s, names)
for i = 1:numel(names)
    if isfield(s, names{i}), s = rmfield(s, names{i}); end
end
end

function ok = local_err_id(fcn, ident)
ok = false;
try
    fcn();
catch ME
    ok = strcmp(ME.identifier, ident);
end
end


function ok = local_acceptance_no_ctrace(ROOT, SBX, vdir, TF) %#ok<INUSD>
% 沙盒：epoch-2 记录缺 ctrace 工件 → 验收必须拒绝；补齐 → 通过
pydir = fullfile(ROOT, 'python');
oldpp = getenv('PYTHONPATH');
setenv('PYTHONPATH', pydir);
cleanup = onCleanup(@() setenv('PYTHONPATH', oldpp)); %#ok<NASGU>
vid = 'QOBS_SYN';
recp = fullfile(vdir, 'C0.json');
rec = jsondecode(fileread(recp));
runrow = struct('T_eval', TF, 'arm', 'C0', 'exec_order', 0, ...
    'run_id', char(rec.run_id), 'voyage_id', vid, 'tier', 'SYNTHETIC', ...
    'split_group_id', 'QOBS');
man = struct('schema', 'ppe_formal_execution_manifest', 'study', 'qobs', ...
    'n_runs', 1, 'n_voyages', 1, 'arms', 'C0', ...
    'execution_order_rule', 'qobs', 'manifest_sha256', 'qobs', ...
    'teval_table_sha256', char(rec.teval_identity_sha256));
man.runs = {runrow};
manp = fullfile(SBX, 'obs_manifest.json');
fid = fopen(manp, 'w');
fwrite(fid, jsonencode(man));
fclose(fid);
bd = struct('checker_v2_sha256', char(rec.checker_v2.sha256), ...
    'teval_table_sha256', char(rec.teval_identity_sha256), ...
    'cstar_composite_sha256', char(rec.cstar_impl_sha256), ...
    'modele_slx_sha256', char(rec.slx_sha256), ...
    'formal_execution_manifest_file_sha256', model.sha256_file(manp));
fz = struct('schema', 'ppe_epoch2_pre_execution_freeze_v3', ...
    'formal_epoch', 2, 'epoch2_result_bearing_runs', 1, 'bindings', bd);
fzp = fullfile(SBX, 'obs_freeze.json');
fid = fopen(fzp, 'w');
fwrite(fid, jsonencode(fz));
fclose(fid);
gate = struct('overall', true, 'freeze_file_sha256', model.sha256_file(fzp));
fid = fopen(fullfile(SBX, 'EPOCH2_PRE_EXECUTION_FREEZE_GATE_V2.json'), 'w');
fwrite(fid, jsonencode(gate));
fclose(fid);
% 缺 warmup parity → 记录会报 parity 缺失；此处验证的是 ctrace 维度，
% parity 由 E2E Q-E2E-16 覆盖 —— 该沙盒断言仅要求 ctrace 缺失被点名。
% 删除控制器迹线工件 → 验收必须在 ctrace 维度拒绝（记录仍在、哈希悬空）
delete(fullfile(vdir, 'C0.ctrace.v1.json'));
out1 = fullfile(SBX, 'acc_no_ctrace.json');
[st1, ~] = system(sprintf(...
    'python3 -m ppe.acceptance_v2 --formal-dir "%s" --freeze "%s" --manifest "%s" --out "%s" --allow-nonproduction', ...
    fileparts(fileparts(recp)), fzp, manp, out1));
a1 = jsondecode(fileread(out1));
named = contains(jsonencode(a1.problems), 'ctrace');
ok = st1 ~= 0 && ~a1.pass && named;
end
